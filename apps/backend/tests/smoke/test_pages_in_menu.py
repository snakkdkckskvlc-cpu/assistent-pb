"""Каждая страница есть в меню. Проход по файлам `views/`, а не по меню.

Продолжение той же истории, что и в `test_pages_reachable.py`, — но дверь
другая. Там ловилось «страница отдаёт 404, потому что имя забыли в списке».
Здесь — «страница открывается по адресу, но попасть на неё некуда»: пункта
в боковой панели нет, а адресную строку сотрудник не набирает, для него
приложение состоит ровно из того, что видно слева.

Случай уже был: «Проверить счёт» прошла все проверки, отвечала 200 и
показывала расхождения — и не существовала для бухгалтера, потому что ссылки
на неё не было ни на одном экране. Прошлый тест этого не видит: с его точки
зрения страница достижима.

Проверка идёт от файлов на диске по той же причине, что и там: список,
составленный вручную, не заметит того, кого в нём нет.

Меню собирается скриптом (`app.js`), автотестов у фронтенда нет — сборки нет
и запускать нечего. Поэтому проверяется факт наличия ссылки в тексте файла,
а не отрисовка. Этого достаточно: забывают именно строку, а не вёрстку.
"""

from __future__ import annotations

import pytest
from fire_safety_backend import config

# Единственная страница без пункта меню — и это осознанно: на форме входа
# боковой панели нет вовсе, показывать с неё ссылки некуда и незачем.
БЕЗ_ПУНКТА_МЕНЮ = {"login"}


def _меню() -> str:
    return (config.FRONTEND_DIR / "app.js").read_text(encoding="utf-8")


def _страницы() -> list[str]:
    return sorted(p.stem for p in (config.FRONTEND_DIR / "views").glob("*.html"))


def test_menu_file_is_where_expected() -> None:
    """Страховка от «зелено, потому что нечего проверять»: если `app.js`
    переедет или меню начнут собирать иначе, проверка ниже станет пустой
    и будет молча пропускать всё подряд."""
    текст = _меню()
    assert "const NAV" in текст, "меню собирается уже не здесь — проверку надо переписать"
    assert len(_страницы()) >= 10


@pytest.mark.parametrize("имя", _страницы())
def test_every_page_has_a_menu_item(имя: str) -> None:
    if имя in БЕЗ_ПУНКТА_МЕНЮ:
        pytest.skip("на форме входа меню нет")
    assert f'"/{имя}.html"' in _меню(), (
        f"views/{имя}.html открывается, но ссылки на неё нет в боковой панели — "
        f"для сотрудника функции не существует, он не набирает адреса руками"
    )
