"""Общий помощник фронтенда объявлен ровно один раз.

Сборки у фронтенда нет, модулей тоже: `app.js` и скрипт страницы попадают в
ОДНУ область имён. Второе объявление с тем же именем не ошибка для браузера —
оно молча перекрывает первое, и побеждает то, чей тег ниже.

Этот тест появился после двух настоящих поломок, найденных в один день.

1. **Две `showError` в самом `app.js`**, с разными сигнатурами: `(ошибка)` и
   `(плашка, ошибка)`. Побеждала нижняя, поэтому вызов одним аргументом — а так
   её звали справочники и транспорт — клал объект ошибки на место плашки и
   падал на `box.style`. Сообщение не показывалось ВОВСЕ: человек нажимал
   «Сохранить», не происходило ничего, и он нажимал ещё раз. Молчаливый отказ,
   который в этом проекте считается худшим видом отказа.

2. **Своя `api` в `waybill.html`**, отставшая от общей. Общая научилась
   переводить замечания проверки на русский, частная — нет, и на экране с
   сотней полей человек видел «[object Object]».

Обе поломки внешне выглядят как рабочий код: имя знакомое, вызовы на месте,
консоль молчит.

Разбор текстовый, а не разбором JS: интерпретатора в проекте нет и заводить его
ради одной проверки — плохая сделка. Отсюда границы: у `app.js` берутся только
объявления с НУЛЕВОЙ колонки (вложенные — свои, они никому не мешают), у
страниц — с любым отступом, потому что скрипт страницы весь лежит внутри тега.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

import pytest

ФРОНТ = Path(__file__).resolve().parents[3] / "desktop" / "frontend"

# Объявление на верхнем уровне: с самого начала строки.
_ВЕРХНИЙ = re.compile(
    r"^(?:async\s+)?function\s+([A-Za-zА-Яа-я_$][\w$]*)\s*\("
    r"|^(?:const|let)\s+([A-Za-zА-Яа-я_$][\w$]*)\s*=\s*(?:async\s*)?(?:\(|function)",
    re.M,
)
# То же самое, но с любым отступом — для скриптов внутри страницы.
_ЛЮБОЙ = re.compile(
    r"^\s*(?:async\s+)?function\s+([A-Za-zА-Яа-я_$][\w$]*)\s*\("
    r"|^\s*(?:const|let)\s+([A-Za-zА-Яа-я_$][\w$]*)\s*=\s*(?:async\s*)?(?:\(|function)",
    re.M,
)

# Пусто намеренно. Если сюда что-то добавляется, рядом пишется ПОЧЕМУ странице
# нужна своя копия общего имени: до сих пор верный ответ был «не нужна».
РАЗРЕШЁННЫЕ_ПОВТОРЫ: dict[str, set[str]] = {}


def _имена(текст: str, шаблон: re.Pattern[str]) -> list[str]:
    return [первое or второе for первое, второе in шаблон.findall(текст)]


def _страницы() -> list[Path]:
    return sorted([*(ФРОНТ / "views").glob("*.html"), ФРОНТ / "index.html"])


def test_app_js_declares_each_helper_once() -> None:
    """Ровно та поломка, что была с `showError`: два объявления в одном файле."""
    имена = _имена((ФРОНТ / "app.js").read_text(encoding="utf-8"), _ВЕРХНИЙ)
    дубли = sorted(имя for имя, сколько in Counter(имена).items() if сколько > 1)
    assert not дубли, (
        f"в app.js объявлены дважды: {дубли}. Второе объявление молча перекроет "
        f"первое, и вызовы уйдут не туда, куда написано"
    )


def test_there_are_helpers_and_pages_to_check() -> None:
    """Страховка от «зелено на пустом множестве»: сломайся разбор — обе
    проверки выше и ниже стали бы бессодержательными, не подав знака."""
    assert len(_имена((ФРОНТ / "app.js").read_text(encoding="utf-8"), _ВЕРХНИЙ)) >= 10
    assert len(_страницы()) >= 10


@pytest.mark.parametrize("страница", _страницы(), ids=lambda p: p.name)
def test_page_does_not_redeclare_shared_helper(страница: Path) -> None:
    """Ровно та поломка, что была с `api` в путевых листах: своя копия общего
    имени, отставшая от оригинала."""
    общие = set(_имена((ФРОНТ / "app.js").read_text(encoding="utf-8"), _ВЕРХНИЙ))
    свои = set(_имена(страница.read_text(encoding="utf-8"), _ЛЮБОЙ))
    столкновения = sorted((свои & общие) - РАЗРЕШЁННЫЕ_ПОВТОРЫ.get(страница.name, set()))
    assert not столкновения, (
        f"{страница.name} объявляет своё: {столкновения}. Эти имена уже есть в "
        f"app.js, области имён общие — копия перекроет общую версию и со "
        f"временем отстанет от неё"
    )
