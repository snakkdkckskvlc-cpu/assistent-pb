"""Сверка двух таблиц.

Здесь проверяется в первую очередь то, что НЕ должно склеиваться. Пропущенное
расхождение — минута работы человека. Ложное совпадение молча превращает две
разные позиции в одну, и отчёт говорит «всё сошлось» там, где не сошлось;
такую ошибку не видно ни на экране, ни в выгрузке.
"""

from __future__ import annotations

import pytest
from fire_safety_backend.services.table_compare import (
    Row,
    compare,
    normalize,
    parse_number,
    similarity,
)

# --- нормализация: что ОБЯЗАНО совпасть ---


@pytest.mark.parametrize(
    "варианты",
    [
        ("Кабель ВВГнг 3х1,5", "кабель ввгнг 3x1.5", "КАБЕЛЬ ВВГ-нг 3*1,5", "Кабель ВВГнг 3 х 1.5"),
        ("Извещатель ИП 212-45", "извещатель ип 212-45", "Извещатель  ИП   212-45 "),
        ("Труба стальная Ø25", "труба стальная Ø25"),
        ("Ёмкость запаса воды", "Емкость запаса воды"),
        ("Кран шаровой (ду 50)", "Кран шаровой ду 50"),
    ],
)
def test_same_position_written_differently(варианты: tuple[str, ...]) -> None:
    ключи = {normalize(v) for v in варианты}
    assert len(ключи) == 1, f"должны совпасть, получилось: {ключи}"


# --- нормализация: что ОБЯЗАНО остаться разным ---


@pytest.mark.parametrize(
    ("a", "b"),
    [
        ("Труба 25", "Труба 32"),
        ("Кабель ВВГнг 3х1,5", "Кабель ВВГнг 3х2,5"),
        ("Извещатель ИП 212-45", "Извещатель ИП 212-46"),
        ("Клапан 25-32", "Клапан 2532"),
    ],
)
def test_different_positions_stay_different(a: str, b: str) -> None:
    """Разница в одном символе — это чаще всего типоразмер, а не описка."""
    assert normalize(a) != normalize(b), f"{a!r} и {b!r} склеились"


def test_decimal_comma_only_between_digits() -> None:
    """Запятая-разделитель разрядов — не то же, что запятая в перечислении."""
    assert normalize("Кабель, лоток") == "кабель лоток"
    assert normalize("3,5") == "3.5"


# --- числа ---


@pytest.mark.parametrize(
    ("raw", "ожидается"),
    [
        ("1 234,56", 123456),
        ("1234.56", 123456),
        ("1 234,56", 123456),  # неразрывный пробел из Excel
        ("1 234,56 ₽", 123456),
        (1234.56, 123456),
        (1234, 123400),
        ("-50,00", -5000),
        ("", None),
        ("—", None),
        (None, None),
        ("нет данных", None),
        (True, None),
    ],
)
def test_parse_money(raw: object, ожидается: int | None) -> None:
    assert parse_number(raw, scale=100) == ожидается


def test_quantity_in_thousandths() -> None:
    assert parse_number("12,5", scale=1000) == 12500


# --- сверка ---


def _r(n: int, name: str, qty: float | None = None, amount: float | None = None) -> Row:
    return Row(
        номер=n,
        название=name,
        количество=None if qty is None else round(qty * 1000),
        сумма=None if amount is None else round(amount * 100),
    )


def test_everything_matches() -> None:
    смета = [_r(1, "Кабель ВВГнг 3х1,5", 100, 5000), _r(2, "Извещатель ИП 212-45", 20, 12000)]
    акт = [_r(1, "кабель ввгнг 3x1.5", 100, 5000), _r(2, "Извещатель ИП 212-45", 20, 12000)]
    отчёт = compare(смета, акт)
    assert отчёт.всё_сошлось
    assert len(отчёт.сошлось) == 2
    assert отчёт.расхождение_итогов == 0


def test_quantity_discrepancy_is_found() -> None:
    """Ровно то, что сегодня ищут глазами вдвоём."""
    отчёт = compare(
        [_r(1, "Кабель ВВГнг 3х1,5", 100, 5000)], [_r(1, "Кабель ВВГнг 3х1,5", 90, 4500)]
    )
    assert not отчёт.всё_сошлось
    assert len(отчёт.расхождения) == 1
    пара = отчёт.расхождения[0]
    assert пара.разница_количества == -10_000  # тысячные доли: минус 10 единиц
    assert пара.разница_суммы == -50_000  # копейки: минус 500 рублей


def test_missing_and_extra_rows() -> None:
    смета = [_r(1, "Кабель ВВГнг 3х1,5"), _r(2, "Труба 25")]
    акт = [_r(1, "Кабель ВВГнг 3х1,5"), _r(2, "Хомут 20")]
    отчёт = compare(смета, акт)
    assert [r.название for r in отчёт.только_слева] == ["Труба 25"]
    assert [r.название for r in отчёт.только_справа] == ["Хомут 20"]


def test_similar_rows_are_candidates_not_matches() -> None:
    """Похожие строки НЕ склеиваются сами — решает человек."""
    отчёт = compare(
        [_r(1, "Кабель ВВГнг 3х1,5 ГОСТ", 10, 100)],
        [_r(1, "Кабель ВВГ нг 3х1,5 по ГОСТ 31996", 10, 100)],
    )
    assert отчёт.сошлось == []
    assert отчёт.расхождения == []
    assert len(отчёт.кандидаты) == 1
    assert отчёт.кандидаты[0].похожесть >= 0.42
    # и обязательно попали в «не сошлось», а не потерялись
    assert not отчёт.всё_сошлось


def test_different_sizes_are_not_even_candidates() -> None:
    """«Труба 25» и «Труба 32» — разные позиции, а не описка.

    Самый опасный случай: строки похожи почти дословно, и любое «умное»
    сопоставление их склеит.
    """
    отчёт = compare([_r(1, "Труба стальная 25")], [_r(1, "Труба стальная 32")])
    assert отчёт.кандидаты == []
    assert len(отчёт.только_слева) == 1
    assert len(отчёт.только_справа) == 1


def test_confirmed_synonym_matches_silently() -> None:
    """Подтверждённое человеком соответствие работает со второго раза молча."""
    слева = [_r(1, "Кабель ВВГнг 3х1,5 ГОСТ", 10, 100)]
    справа = [_r(1, "Кабель ВВГ нг 3х1,5 по ГОСТ 31996", 10, 100)]
    синонимы = {
        normalize("Кабель ВВГ нг 3х1,5 по ГОСТ 31996"): normalize("Кабель ВВГнг 3х1,5 ГОСТ")
    }
    отчёт = compare(слева, справа, синонимы=синонимы)
    assert len(отчёт.сошлось) == 1
    assert отчёт.кандидаты == []
    assert отчёт.всё_сошлось


def test_duplicates_are_set_aside_not_guessed() -> None:
    """Позиция дважды в одной таблице — неизвестно, какую строку сверять.

    Любой выбор здесь был бы выдумкой, поэтому обе строки выносятся человеку.
    """
    отчёт = compare(
        [_r(1, "Кабель ВВГнг 3х1,5", 10, 100)],
        [_r(1, "Кабель ВВГнг 3х1,5", 4, 40), _r(2, "кабель ввгнг 3x1.5", 6, 60)],
    )
    assert len(отчёт.дубли_справа) == 2
    assert отчёт.сошлось == []
    assert not отчёт.всё_сошлось

    # Строка не может быть ОДНОВРЕМЕННО дублем и сопоставленной. Раньше тест
    # этого не проверял, и мутация «не убирать дубли из словаря» проходила
    # незамеченной: первая из двух строк и оставалась парой, и лежала в
    # дублях — то есть попадала в итог ДВАЖДЫ.
    assert отчёт.расхождения == [], "дубль не должен образовывать пару"
    assert отчёт.кандидаты == []
    assert отчёт.итог_справа == 10_000, "40 + 60 рублей, каждая строка ровно один раз"
    assert отчёт.итог_слева == 10_000


def test_totals_count_every_row() -> None:
    """Итог обязан включать и несопоставленные строки — иначе он врёт
    ровно в том случае, ради которого сверку и запускают."""
    отчёт = compare(
        [_r(1, "Кабель", 1, 100), _r(2, "Труба 25", 1, 50)],
        [_r(1, "Кабель", 1, 100)],
    )
    assert отчёт.итог_слева == 15000  # 150 рублей в копейках
    assert отчёт.итог_справа == 10000
    assert отчёт.расхождение_итогов == -5000


def test_empty_tables() -> None:
    отчёт = compare([], [])
    assert отчёт.всё_сошлось
    assert отчёт.итог_слева == 0


def test_rows_without_name_are_ignored() -> None:
    """Пустые строки и итоговые разделители в выгрузках — обычное дело."""
    отчёт = compare([_r(1, ""), _r(2, "   "), _r(3, "Кабель", 1, 100)], [_r(1, "Кабель", 1, 100)])
    assert отчёт.всё_сошлось
    assert len(отчёт.сошлось) == 1


def test_missing_numbers_do_not_fake_agreement() -> None:
    """Пустое количество — это «неизвестно», а не «ноль»."""
    отчёт = compare([_r(1, "Кабель", None, 100)], [_r(1, "Кабель", 5, 100)])
    пара = (отчёт.сошлось + отчёт.расхождения)[0]
    assert пара.разница_количества is None


def test_similarity_bounds() -> None:
    assert similarity("кабель", "кабель") == 1.0
    assert similarity("", "кабель") == 0.0
    assert 0.0 <= similarity("труба 25", "труба 32") <= 1.0
