def test_line_multiplication_error(tmp_path: Path) -> None:
    """Классика: цену поменяли, сумму пересчитать забыли."""
    путь = _счёт(
        tmp_path,
        [
            [1, "Кабель ВВГнг 3х1,5", "м", 100, 52, 5000],  # должно быть 5200
            [2, "Извещатель ИП 212-45", "шт", 20, 600, 12000],
        ],
        [["", "ИТОГО", "", "", "", 17000]],
    )
    итог = проверить(read_table(путь))
    строки = [p for p in итог.проблемы if p.где == "строка"]
    assert len(строки) == 1
    assert "Кабель" in строки[0].что
    assert строки[0].ожидалось == 520_000
    assert строки[0].в_документе == 500_000
    assert строки[0].разница == -20_000  # недосчитали 200 рублей
    assert строки[0].строка == 4


