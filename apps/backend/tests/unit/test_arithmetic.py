"""Проверка арифметики в счёте и акте.

Тут важнее обычного, чтобы проверка не срабатывала зря. Бухгалтер получает
список расхождений; если половина из них выдумана округлением, он перестанет
читать список целиком — и пропустит настоящую ошибку. Поэтому ложных
срабатываний проверяется столько же, сколько настоящих находок.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from fire_safety_backend.infrastructure.parsers.xlsx_parser import read_table
from fire_safety_backend.services.arithmetic import проверить, прописью
from openpyxl import Workbook


def _файл(rows: list[list[object]], path: Path) -> Path:
    wb = Workbook()
    ws = wb.active
    for row in rows:
        ws.append(row)
    wb.save(path)
    return path


ШАПКА = ["№", "Наименование", "Ед.", "Количество", "Цена", "Сумма"]


def _счёт(
    tmp_path: Path, строки: list[list[object]], хвост: list[list[object]] | None = None
) -> Path:
    rows = [["СЧЁТ на оплату № 412"], [], ШАПКА, *строки, *(хвост or [])]
    return _файл(rows, tmp_path / "счёт.xlsx")


# --- сумма прописью ---


@pytest.mark.parametrize(
    ("копейки", "ожидается"),
    [
        (0, "ноль рублей 00 копеек"),
        (100, "один рубль 00 копеек"),
        (200, "два рубля 00 копеек"),
        (500, "пять рублей 00 копеек"),
        (123456, "одна тысяча двести тридцать четыре рубля 56 копеек"),
        (200000, "две тысячи рублей 00 копеек"),
        (500000, "пять тысяч рублей 00 копеек"),
        (1100000, "одиннадцать тысяч рублей 00 копеек"),
        (2921000, "двадцать девять тысяч двести десять рублей 00 копеек"),
        (100000000, "один миллион рублей 00 копеек"),
        (10101, "сто один рубль 01 копейка"),
        (20402, "двести четыре рубля 02 копейки"),
    ],
)
def test_number_in_words(копейки: int, ожидается: str) -> None:
    """Женский род у тысяч и склонения — это то, на чём такие функции обычно
    и врут: «два тысячи», «одна рублей»."""
    assert прописью(копейки) == ожидается


# --- когда всё сходится, жаловаться не на что ---


def test_correct_invoice_has_no_complaints(tmp_path: Path) -> None:
    путь = _счёт(
        tmp_path,
        [
            [1, "Кабель ВВГнг 3х1,5", "м", 100, 50, 5000],
            [2, "Извещатель ИП 212-45", "шт", 20, 600, 12000],
        ],
        [
            ["", "ИТОГО", "", "", "", 17000],
            ["", "Всего к оплате: семнадцать тысяч рублей 00 копеек"],
        ],
    )
    итог = проверить(read_table(путь))
    assert итог.всё_сходится, [p.что for p in итог.проблемы]
    assert итог.строк_проверено == 2
    assert итог.сумма_строк == 1_700_000


def test_kopeck_rounding_is_not_an_error(tmp_path: Path) -> None:
    """Копейка расхождения — округление, а не ошибка.

    Если жаловаться на неё, список расхождений станет нечитаемым, и настоящую
    ошибку в нём пропустят.
    """
    путь = _счёт(
        tmp_path,
        # 3 × 33,33 = 99,99, а в документе 100,00 — это округление
        [[1, "Мелочь", "шт", 3, 33.33, 100.00]],
        [["", "ИТОГО", "", "", "", 100.00]],
    )
    итог = проверить(read_table(путь))
    assert итог.всё_сходится, [p.что for p in итог.проблемы]


