def test_vat_inside_the_total(tmp_path: Path) -> None:
    """«В том числе НДС 20%» — налог сидит ВНУТРИ суммы.

    Считать его как 20% от итога — самая частая ошибка: получится больше, чем
    на самом деле.
    """
    путь = _счёт(
        tmp_path,
        [[1, "Кабель", "м", 100, 100, 10000]],
        [
            ["", "ИТОГО", "", "", "", 10000],
            ["", "в том числе НДС 20%", "", "", "", 2000],  # верно 1666,67
        ],
    )
    итог = проверить(read_table(путь))
    ндс = [p for p in итог.проблемы if p.где == "ндс"]
    assert len(ндс) == 1
    assert ндс[0].ожидалось == 166_667
    assert ндс[0].в_документе == 200_000


