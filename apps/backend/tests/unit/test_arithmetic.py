def test_similar_amount_does_not_slip_through(tmp_path: Path) -> None:
    """Ловушка: «два рубля» — это часть фразы «двадцать два рубля».

    Если сравнивать «содержится ли», документ на двадцать два рубля прошёл бы
    проверку на два. Поэтому сумма из фразы вырезается целиком.
    """
    путь = _счёт(
        tmp_path,
        [[1, "Мелочь", "шт", 1, 2, 2]],  # два рубля
        [
            ["", "ИТОГО", "", "", "", 2],
            ["", "Сумма прописью: двадцать два рубля 00 копеек"],
        ],
    )
    итог = проверить(read_table(путь))
    прописи = [p for p in итог.проблемы if p.где == "прописью"]
    assert len(прописи) == 1, "расхождение обязано быть замечено"


