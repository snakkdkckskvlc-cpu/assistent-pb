"""Контрольные суммы реквизитов.

Опорная точка тестов — НАСТОЯЩИЕ реквизиты ООО «ПожСервис» с фирменного бланка
(`resources/templates/letterhead.docx`) и из сидов организаций. Если алгоритм
объявит их испорченными, неправ алгоритм, а не бланк. Выдуманные «валидные»
номера такой опоры не дают: их подгоняют под реализацию, и ошибка в реализации
уезжает в тест вместе с номером.

База и сеть здесь не нужны — все функции чистые, поэтому фикстура `client` не
берётся намеренно.
"""

from __future__ import annotations

import pytest
from fire_safety_backend.services import requisites as r

# Реквизиты с бланка. Публикации не подлежат, но в коде проекта они уже есть —
# в letterhead.docx и в сидах services/waybills.py.
ИНН = "4823026435"
КПП = "482301001"
БИК = "040173604"
СЧЁТ = "40702810435000105037"
ОГРН = "1054800315184"


def test_real_company_requisites_are_valid() -> None:
    """Главный тест файла: живые реквизиты обязаны проходить."""
    assert r.проверить_инн(ИНН)
    assert r.проверить_кпп(КПП)
    assert r.проверить_бик(БИК)
    assert r.проверить_счёт(СЧЁТ, БИК)
    assert r.проверить_огрн(ОГРН)


def test_empty_value_is_not_an_error() -> None:
    """Обязательность решает форма, а не проверка: иначе карточку нельзя было
    бы заполнять по частям."""
    for проверка in (
        r.проверить_инн,
        r.проверить_кпп,
        r.проверить_бик,
        r.проверить_огрн,
        r.проверить_окпо,
        r.проверить_снилс,
    ):
        assert проверка(""), проверка.__name__
        assert проверка(None), проверка.__name__
    assert r.проверить_счёт("", БИК)


def test_spaces_and_dashes_are_tolerated() -> None:
    """Реквизиты копируют из писем и договоров, а там они с разделителями."""
    assert r.проверить_инн("4823 026 435")
    assert r.проверить_счёт("40702810 4350 0010 5037", "040-173-604")
    assert r.проверить_снилс("112-233-445 95") == r.проверить_снилс("11223344595")


@pytest.mark.parametrize("плохой", ["48230264352", "482302643", "48230264ХХ"])
def test_inn_of_wrong_length_is_rejected(плохой: str) -> None:
    assert not r.проверить_инн(плохой)


def test_inn_catches_every_single_digit_error() -> None:
    """Замеренное свойство, а не предположение: по настоящему ИНН перебираются
    все замены одной цифры и все перестановки соседних."""
    поймано, всего = _перебор(ИНН, r.проверить_инн)
    assert поймано == всего, f"ИНН пропустил {всего - поймано} испорченных из {всего}"


def test_ogrn_catches_every_single_digit_error() -> None:
    поймано, всего = _перебор(ОГРН, r.проверить_огрн)
    assert поймано == всего, f"ОГРН пропустил {всего - поймано} из {всего}"


def test_account_catches_most_but_not_all() -> None:
    """ЗАМЕР, а не обещание. Контрольная сумма счёта — по модулю 10, и часть
    перестановок она пропускает: на настоящем счёте ловится 34 из 37 порч.

    Записано тестом намеренно. Если однажды покажется, что «счёт проверен» —
    здесь видно, что нет: проверка ловит опечатку, но не заменяет сверку с
    договором. Три пропущенных перестановки перечислены ниже поимённо.
    """
    поймано, всего = _перебор(СЧЁТ, lambda x: r.проверить_счёт(x, БИК))
    assert (поймано, всего) == (34, 37)

    for пропущенный in (
        "40702810430500105037",  # перестановка 11-12
        "40702810435000150037",  # перестановка 16-17
        "40702810435000100537",  # перестановка 17-18
    ):
        assert r.проверить_счёт(пропущенный, БИК), "замер устарел — пересчитайте цифры в тесте"


def test_account_needs_bik() -> None:
    """Контрольная сумма счёта считается с тремя цифрами из БИК, поэтому в
    отрыве от банка счёт не проверяется вовсе — и об этом говорится прямо."""
    ответ = r.проверить_счёт(СЧЁТ, "")
    assert not ответ
    assert "БИК" in ответ.причина


def test_correspondent_account_uses_other_digits_of_bik() -> None:
    """У корсчёта (301…) в контрольную сумму идут другие знаки БИК. Перепутать
    нельзя: правильный счёт объявил бы себя испорченным."""
    корсчёт = "30101810200000000604"
    assert r.проверить_счёт(корсчёт, БИК)


def test_bik_must_be_russian() -> None:
    assert not r.проверить_бик("140173604")
    assert not r.проверить_бик("04017360")


def test_kpp_allows_latin_letters_in_the_middle() -> None:
    """Пятый и шестой знак бывают латинскими — так учитывают иностранные
    организации. Отвергать их значит не дать завести такого контрагента."""
    assert r.проверить_кпп("4823AB001")
    assert not r.проверить_кпп("4823АБ001"), "кириллица в КПП недопустима"
    assert not r.проверить_кпп("48230100")


def test_snils_control_number() -> None:
    assert r.проверить_снилс("112-233-445 95")
    assert not r.проверить_снилс("112-233-445 96")
    assert not r.проверить_снилс("1122334459")


def test_old_snils_without_control_number_is_accepted() -> None:
    """Номера младше 001-001-998 контрольного числа не имеют. Это не ошибка, а
    исторические номера, и отвергать их нельзя — водитель с таким СНИЛС не
    смог бы попасть в справочник."""
    assert r.проверить_снилс("00100199700")


def test_okpo_second_pass() -> None:
    """Второй проход со сдвинутыми весами — часть алгоритма, а не запасной
    путь. Проверяется на числе, где первый проход даёт остаток 10."""
    assert r.проверить_окпо("00000000")
    assert not r.проверить_окпо("12345")


def _перебор(номер: str, проверка) -> tuple[int, int]:
    """Сколько испорченных вариантов поймано из скольких.

    Две самые частые опечатки при наборе с бумаги: перестановка соседних цифр
    и замена одной цифры.
    """
    испорченные = [
        номер[:i] + номер[i + 1] + номер[i] + номер[i + 2 :]
        for i in range(len(номер) - 1)
        if номер[i] != номер[i + 1]
    ]
    испорченные += [
        номер[:i] + str((int(ц) + 1) % 10) + номер[i + 1 :] for i, ц in enumerate(номер)
    ]
    поймано = sum(1 for x in испорченные if not проверка(x))
    return поймано, len(испорченные)
