"""Проверка реквизитов сразу во всей таблице.

Опора та же, что и у теста контрольных сумм: НАСТОЯЩИЕ реквизиты
ООО «ПожСервис». Если проход по таблице объявит их испорченными — неправ
проход, а не бланк.

Половина файла проверяет обратное: что программа МОЛЧИТ там, где всё в
порядке. Ложная тревога здесь дороже пропуска — после третьей человек
перестаёт открывать экран, и тогда не работает уже ничего.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from fire_safety_backend.services import requisites_table as rt
from openpyxl import Workbook

# Реквизиты с фирменного бланка — те же, что в test_requisites.py.
ИНН = "4823026435"
КПП = "482301001"
БИК = "040173604"
СЧЁТ = "40702810435000105037"
ОГРН = "1054800315184"


def _файл(tmp_path: Path, строки: list[list[object]], имя: str = "т.xlsx") -> Path:
    книга = Workbook()
    лист = книга.active
    for строка in строки:
        лист.append(строка)
    путь = tmp_path / имя
    книга.save(путь)
    return путь


# --- Главное: на правильном файле программа молчит ---


def test_real_requisites_pass(tmp_path: Path) -> None:
    путь = _файл(
        tmp_path,
        [
            ["Контрагент", "ИНН", "КПП", "БИК", "Расчётный счёт", "ОГРН"],
            ["ООО ПожСервис", ИНН, КПП, БИК, СЧЁТ, ОГРН],
        ],
    )
    итог = rt.проверить(путь)
    assert итог.всё_сходится, [p.что for p in итог.проблемы]
    assert итог.строк == 1


def test_empty_cells_are_not_errors(tmp_path: Path) -> None:
    """Реестр заполняют по частям. Пустая клетка — не ошибка реквизита."""
    путь = _файл(tmp_path, [["Контрагент", "ИНН", "КПП"], ["ООО Ромашка", None, ""]])
    assert rt.проверить(путь).всё_сходится


def test_header_only_file_is_quiet(tmp_path: Path) -> None:
    путь = _файл(tmp_path, [["Контрагент", "ИНН"]])
    итог = rt.проверить(путь)
    assert итог.всё_сходится
    assert итог.строк == 0


# --- Находки ---


def test_broken_inn_is_found(tmp_path: Path) -> None:
    """Переставлены две соседние цифры — номер той же длины, глазами не видно."""
    битый = ИНН[:4] + ИНН[5] + ИНН[4] + ИНН[6:]
    assert битый != ИНН
    путь = _файл(tmp_path, [["Контрагент", "ИНН"], ["ООО Ромашка", битый]])
    итог = rt.проверить(путь)
    assert итог.всего_проблем == 1
    p = итог.проблемы[0]
    assert p.вид == "ИНН"
    assert p.строка == 2
    assert p.колонка == "B"
    assert p.заголовок == "ИНН"


def test_account_is_checked_against_bik(tmp_path: Path) -> None:
    """Контрольная цифра счёта считается вместе с БИК — в этом весь смысл."""
    битый = СЧЁТ[:-1] + ("0" if СЧЁТ[-1] != "0" else "1")
    путь = _файл(
        tmp_path,
        [["Банк", "БИК", "Расчётный счёт"], ["Сбер", БИК, битый]],
    )
    итог = rt.проверить(путь)
    assert [p.вид for p in итог.проблемы] == ["Счёт"]


def test_account_without_bik_column_says_so(tmp_path: Path) -> None:
    """Молчаливая деградация запрещена: без БИК счёт полноценно не проверить,
    и человек должен это узнать, а не решить, что счёт хороший."""
    путь = _файл(tmp_path, [["Контрагент", "Расчётный счёт"], ["ООО Ромашка", СЧЁТ]])
    итог = rt.проверить(путь)
    assert any("БИК" in з for з in итог.заметки)


def test_snils_and_ogrn_are_checked(tmp_path: Path) -> None:
    """112-233-445 95 — настоящий СНИЛС: 9+8+14+12+15+12+12+8+5 = 95. Ошибся я,
    когда писал этот тест «с заведомо неверным числом», а не программа —
    поэтому здесь два номера: правильный обязан молчать, испорченный найтись.
    """
    путь = _файл(
        tmp_path,
        [
            ["Водитель", "СНИЛС", "ОГРН"],
            ["Иванов", "112-233-445 95", ОГРН],
            ["Петров", "112-233-445 96", ОГРН],
        ],
    )
    проблемы = rt.проверить(путь).проблемы
    assert [(p.строка, p.вид) for p in проблемы] == [(3, "СНИЛС")]


