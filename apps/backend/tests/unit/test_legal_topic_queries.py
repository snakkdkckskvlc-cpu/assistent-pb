"""Второй запрос к базе норм подбирается ПОД РАЗДЕЛ части договора.

Раньше он был константой «ответственность неустойка штраф убытки», и в
контекст части про приёмку ехали статьи про неустойку. Контекст в такой
ситуации не нейтрален — он подсказывает модели, о чём писать: на разрезе 40
эталонных рисков разделы «Приёмка, гарантия, сроки, споры» дали 0 находок из
8, при 12 из 14 по ответственности.

См. pipelines/legal.py::_topic_queries_for и docs/05-quality/
improvements-backlog.md, пункт 1.6.
"""

from __future__ import annotations

import pytest
from fire_safety_backend.pipelines.legal import (
    _DEFAULT_TOPIC_QUERY,
    _MAX_TOPIC_QUERIES,
    _topic_queries_for,
)


@pytest.mark.parametrize(
    ("part", "expected_word"),
    [
        ("5.1. Приёмка выполненных работ производится по акту.", "приёмка"),
        ("6.2. Гарантийный срок на смонтированную АПС — 12 месяцев.", "гарантийный"),
        ("9.4. Заказчик вправе отказаться от исполнения Договора.", "отказ"),
        ("11.1. Споры передаются в арбитражный суд по месту Заказчика.", "споров"),
        ("3.2. Оплата производится в течение 90 дней после подписания акта.", "оплаты"),
        ("4.1. Срок выполнения работ — 30 дней с даты аванса.", "сроки"),
    ],
)
def test_query_follows_section_topic(part: str, expected_word: str) -> None:
    queries = _topic_queries_for(part)
    assert any(expected_word in q for q in queries), queries


def test_part_without_known_topic_falls_back_to_liability() -> None:
    """Ответственность — самый частый источник рисков, ей и закрываем пробел."""
    assert _topic_queries_for("1.1. Настоящий Договор заключён в г. Липецке.") == [
        _DEFAULT_TOPIC_QUERY
    ]


def test_number_of_queries_is_capped() -> None:
    """Итоговый контекст всё равно режется до трёх чанков.

    Баллы нормализуются ВНУТРИ выдачи каждого запроса и между запросами
    несравнимы, поэтому чем больше выдач сливается в одну, тем меньше смысла
    в сортировке по score. Часть, задевающая сразу пять разделов, не должна
    превращать отбор норм в лотерею.
    """
    part = (
        "5.1. Приёмка работ по акту. 6.2. Гарантийный срок 12 месяцев. "
        "9.4. Отказ от договора в одностороннем порядке. 11.1. Споры в суде. "
        "3.2. Оплата в течение 90 дней. 4.1. Срок выполнения работ 30 дней."
    )
    assert len(_topic_queries_for(part)) == _MAX_TOPIC_QUERIES


def test_topics_are_ranked_by_frequency_not_by_list_order() -> None:
    """Приоритет определяет ТЕКСТ, а не порядок строк в исходнике.

    На этом правка чуть не сломалась. Договор целиком задевает все восемь
    разделов сразу, и отбор «первые совпавшие» давал на всех пяти фикстурах
    одну и ту же пару «приёмка + гарантия» — просто потому, что эти строки
    объявлены выше. Нормы про неустойку при этом пропадали из контекста
    вовсе, то есть для короткого договора правка была бы ХУЖЕ прежней
    константы.
    """
    # Приёмка объявлена в списке первой, но текст почти весь про санкции.
    part = (
        "5.1. Приёмка работ по акту. "
        "7.1. Неустойка за просрочку. 7.2. Штраф 10%. 7.3. Убытки сверх неустойки. "
        "7.4. Ответственность Подрядчика. 7.5. Неустойка не ограничена."
    )
    assert "неустойка" in _topic_queries_for(part)[0]


def test_query_is_never_empty() -> None:
    """Пустой запрос к гибридному поиску вернул бы пустую выдачу молча."""
    for part in ("", "   ", "\n\n"):
        assert all(q.strip() for q in _topic_queries_for(part))


def test_yo_and_e_spelling_both_recognised() -> None:
    """В договорах «приемка» и «расчет» без «ё» — норма, а не опечатка."""
    assert _topic_queries_for("5.1. Приемка работ") != [_DEFAULT_TOPIC_QUERY]
    assert _topic_queries_for("3.1. Порядок расчетов") != [_DEFAULT_TOPIC_QUERY]
