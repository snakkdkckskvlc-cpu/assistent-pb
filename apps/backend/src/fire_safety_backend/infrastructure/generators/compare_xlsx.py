"""Отчёт о сверке двух таблиц — в Excel, потому что дальше с ним работают в нём.

Отчёт разложен по листам, а не свален в один: человек открывает файл с
конкретным вопросом («что не сошлось по количеству», «чего нет в акте»), и
листать ради этого общую простыню — та же работа, которую сверка и снимает.

Первым листом идёт «Итог», и на нём же написано, чего программа НЕ знает:
нерешённые кандидаты и предупреждения разбора. Отчёт, который выглядит полным,
но молчит о догадках, хуже отсутствия отчёта — по нему подпишут.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

if TYPE_CHECKING:
    from pathlib import Path

    from ...services.table_compare import Отчёт

# Заливки. Красная — расхождение, жёлтая — требует решения человека, серая —
# шапка. Цвета взяты близко к палитре приложения, чтобы отчёт не выглядел
# чужим документом.
_ЗАГОЛОВОК = PatternFill("solid", fgColor="27323D")
_ПЛОХО = PatternFill("solid", fgColor="FDE7E8")
_РЕШИТЬ = PatternFill("solid", fgColor="FFF6E0")
_БЕЛЫЙ = Font(color="FFFFFF", bold=True)

_ДЕНЬГИ = "# ##0.00"
_КОЛИЧЕСТВО = "# ##0.###"


def _пар(n: int) -> str:
    """«1 пара», «2 пары», «5 пар». Текст читает бухгалтер, а не программист."""
    сотня, десяток = n % 100, n % 10
    if 11 <= сотня <= 14:
        форма = "пар"
    elif десяток == 1:
        форма = "пара"
    elif 2 <= десяток <= 4:
        форма = "пары"
    else:
        форма = "пар"
    return f"{n} {форма}"


def _рубли(kop: int | None) -> float | None:
    return None if kop is None else kop / 100


def _штуки(x1000: int | None) -> float | None:
    return None if x1000 is None else x1000 / 1000


def _шапка(ws, названия: list[str]) -> None:
    ws.append(названия)
    for cell in ws[1]:
        cell.fill = _ЗАГОЛОВОК
        cell.font = _БЕЛЫЙ
        cell.alignment = Alignment(vertical="center", wrap_text=True)
    ws.freeze_panes = "A2"


def _ширины(ws, ширины: list[int]) -> None:
    for i, w in enumerate(ширины, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def _числовой_формат(ws, колонки: dict[int, str], с_строки: int = 2) -> None:
    for row in ws.iter_rows(min_row=с_строки):
        for cell in row:
            fmt = колонки.get(cell.column)
            if fmt and isinstance(cell.value, int | float):
                cell.number_format = fmt


def build_compare_xlsx(
    отчёт: Отчёт,
    dest: Path,
    *,
    имя_слева: str = "Файл 1",
    имя_справа: str = "Файл 2",
    предупреждения: list[str] | None = None,
) -> Path:
    """Собирает книгу отчёта. `dest` — уже открытый на запись путь."""
    wb = Workbook()

    # --- Итог ---
    ws = wb.active
    ws.title = "Итог"
    ws.append(["Сверка таблиц"])
    ws["A1"].font = Font(bold=True, size=14)
    ws.append([])
    ws.append(["Слева", имя_слева])
    ws.append(["Справа", имя_справа])
    ws.append([])
    ws.append(["Показатель", "Строк", "Сумма, ₽"])
    for cell in ws[6]:
        cell.fill = _ЗАГОЛОВОК
        cell.font = _БЕЛЫЙ

    строки_итога = [
        ("Сошлось", len(отчёт.сошлось), None),
        ("Расходится", len(отчёт.расхождения), None),
        (f"Только в «{имя_слева}»", len(отчёт.только_слева), None),
        (f"Только в «{имя_справа}»", len(отчёт.только_справа), None),
        ("Похожие — нужно решение", len(отчёт.кандидаты), None),
        ("Повторяются внутри файла", len(отчёт.дубли_слева) + len(отчёт.дубли_справа), None),
        (None, None, None),
        (f"Итого по «{имя_слева}»", None, _рубли(отчёт.итог_слева)),
        (f"Итого по «{имя_справа}»", None, _рубли(отчёт.итог_справа)),
        ("Разница итогов", None, _рубли(отчёт.расхождение_итогов)),
    ]
    for название, строк, сумма in строки_итога:
        ws.append([название, строк, сумма])
    # Разницу итогов подсвечиваем, если она не ноль: это то, ради чего открывают
    # файл, и она не должна теряться среди строк.
    if отчёт.расхождение_итогов:
        for cell in ws[ws.max_row]:
            cell.fill = _ПЛОХО
        ws.cell(row=ws.max_row, column=1).font = Font(bold=True)

    ws.append([])
    вывод = (
        "Расхождений не найдено"
        if отчёт.всё_сошлось
        else "Есть расхождения — смотрите листы отчёта"
    )
    ws.append([вывод])
    ws.cell(row=ws.max_row, column=1).font = Font(bold=True)

    for w in предупреждения or []:
        ws.append([f"Внимание: {w}"])
        for cell in ws[ws.max_row]:
            cell.fill = _РЕШИТЬ
    if отчёт.кандидаты:
        ws.append(
            [
                f"Внимание: {_пар(len(отчёт.кандидаты))} похожи, но программа их не "
                "сопоставила — решение за человеком, лист «Похожие»."
            ]
        )
        for cell in ws[ws.max_row]:
            cell.fill = _РЕШИТЬ

    _ширины(ws, [46, 10, 16])
    _числовой_формат(ws, {3: _ДЕНЬГИ}, с_строки=7)

    # --- Расхождения ---
    ws = wb.create_sheet("Расхождения")
    _шапка(
        ws,
        [
            "Наименование",
            f"Строка в «{имя_слева}»",
            f"Кол-во «{имя_слева}»",
            f"Кол-во «{имя_справа}»",
            "Разница кол-ва",
            f"Сумма «{имя_слева}», ₽",
            f"Сумма «{имя_справа}», ₽",
            "Разница суммы, ₽",
        ],
    )
    for п in отчёт.расхождения:
        ws.append(
            [
                п.слева.название,
                п.слева.номер,
                _штуки(п.слева.количество),
                _штуки(п.справа.количество),
                _штуки(п.разница_количества),
                _рубли(п.слева.сумма),
                _рубли(п.справа.сумма),
                _рубли(п.разница_суммы),
            ]
        )
        for cell in ws[ws.max_row]:
            cell.fill = _ПЛОХО
    _ширины(ws, [46, 12, 14, 14, 14, 16, 16, 16])
    _числовой_формат(
        ws, {3: _КОЛИЧЕСТВО, 4: _КОЛИЧЕСТВО, 5: _КОЛИЧЕСТВО, 6: _ДЕНЬГИ, 7: _ДЕНЬГИ, 8: _ДЕНЬГИ}
    )

    # --- Только в одном файле ---
    for title, rows in (
        (f"Нет в «{имя_справа}»", отчёт.только_слева),
        (f"Нет в «{имя_слева}»", отчёт.только_справа),
    ):
        # Имя листа в Excel не длиннее 31 символа и без части знаков.
        ws = wb.create_sheet(title[:31].replace("/", "-").replace("\\", "-"))
        _шапка(ws, ["Наименование", "Строка в файле", "Количество", "Сумма, ₽"])
        for r in rows:
            ws.append([r.название, r.номер, _штуки(r.количество), _рубли(r.сумма)])
        _ширины(ws, [46, 14, 14, 16])
        _числовой_формат(ws, {3: _КОЛИЧЕСТВО, 4: _ДЕНЬГИ})

    # --- Похожие ---
    ws = wb.create_sheet("Похожие")
    ws.append(
        [
            "Программа НЕ сопоставила эти строки сама. Проверьте: если это одна "
            "позиция, подтвердите — второй раз спрашивать не будет."
        ]
    )
    ws["A1"].font = Font(italic=True)
    ws.append([])
    ws.append([f"В «{имя_слева}»", "Строка", f"В «{имя_справа}»", "Строка", "Похожесть"])
    for cell in ws[3]:
        cell.fill = _ЗАГОЛОВОК
        cell.font = _БЕЛЫЙ
    for к in отчёт.кандидаты:
        ws.append(
            [
                к.слева.название,
                к.слева.номер,
                к.справа.название,
                к.справа.номер,
                round(к.похожесть, 2),
            ]
        )
        for cell in ws[ws.max_row]:
            cell.fill = _РЕШИТЬ
    _ширины(ws, [40, 10, 40, 10, 12])

    # --- Повторы ---
    if отчёт.дубли_слева or отчёт.дубли_справа:
        ws = wb.create_sheet("Повторы")
        ws.append(
            [
                "Эти позиции встречаются в своём файле больше одного раза. "
                "Пока они не объединены, сверить их не с чем: неизвестно, какую "
                "строку с какой сравнивать."
            ]
        )
        ws["A1"].font = Font(italic=True)
        ws.append([])
        ws.append(["Файл", "Наименование", "Строка", "Количество", "Сумма, ₽"])
        for cell in ws[3]:
            cell.fill = _ЗАГОЛОВОК
            cell.font = _БЕЛЫЙ
        for имя, rows in ((имя_слева, отчёт.дубли_слева), (имя_справа, отчёт.дубли_справа)):
            for r in rows:
                ws.append([имя, r.название, r.номер, _штуки(r.количество), _рубли(r.сумма)])
        _ширины(ws, [20, 40, 10, 14, 16])
        _числовой_формат(ws, {4: _КОЛИЧЕСТВО, 5: _ДЕНЬГИ}, с_строки=4)

    wb.save(str(dest))
    return dest
