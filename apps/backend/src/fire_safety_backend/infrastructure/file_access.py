"""Границы записи: приложение изменяет файлы только в своей рабочей папке.

Требование простое: приложение не должно уметь испортить или удалить документ,
который ему не передавали. Файл попадает к нему одним способом — через
интерфейс, и тогда он лежит в data/uploads; результат приложение кладёт в
data/outputs; расшифрованные копии на время обработки — в data/tmp. Всё
остальное на диске для него посторонее.

Сейчас это и так соблюдается (обход всех write_bytes/unlink/rmtree в коде это
подтвердил), поэтому модуль не исправляет утечку, а ЗАКРЕПЛЯЕТ инвариант:
любая будущая правка, которая начнёт писать наружу, упадёт на тесте, а не
испортит документы у заказчика.

Чего здесь нет намеренно:

- **Ограничений на чтение.** Запись и удаление — то, что необратимо портит
  документы; чтение решено отдельным вопросом (справочная папка «только
  чтение» на сервере) и пока отложено.
- **Ограничения на скачивание.** Путь сохранения приходит из НАТИВНОГО
  диалога Windows (`create_file_dialog` в fire_safety_desktop/main.py::_Api),
  из JS — только предлагаемое имя. То есть каталог выбирает человек, и
  запрещать ему сохранять куда он хочет было бы не защитой, а поломкой.
- **Ограничений для скриптов.** `scripts/index_letters.py --dir` читает архивы
  по произвольным путям, их запускает разработчик руками.
"""

from __future__ import annotations

from pathlib import Path

from .. import config


class AccessDenied(PermissionError):
    """Попытка записать или удалить файл вне рабочей папки приложения."""


def writable_roots() -> tuple[Path, ...]:
    """Каталоги, в которых приложению разрешено создавать и удалять файлы.

    Читаются из config при каждом вызове, а не кешируются: тесты подменяют эти
    пути на временные, и закешированный список сделал бы проверку либо
    бесполезной, либо ложно срабатывающей.

    Именно эти три, а не DATA_DIR целиком: data/chroma и data/app.db живут
    своей жизнью (ChromaDB и sqlite), и документному слою там писать нечего.
    """
    return (
        config.UPLOAD_DIR.resolve(),
        config.OUTPUT_DIR.resolve(),
        config.WORK_DIR.resolve(),
    )


def _resolve(path: Path) -> Path:
    """Абсолютный путь без `..` и симлинков.

    resolve() обязателен, а не «для красоты»: без него `data/uploads/../../..`
    и junction на Windows пройдут проверку — строка начинается с разрешённого
    каталога, а файл окажется где угодно.
    """
    return Path(path).resolve()


def is_writable(path: Path) -> bool:
    resolved = _resolve(path)
    return any(resolved == root or resolved.is_relative_to(root) for root in writable_roots())


def assert_writable(path: Path) -> Path:
    """Возвращает нормализованный путь либо бросает AccessDenied."""
    resolved = _resolve(path)
    if is_writable(resolved):
        return resolved
    allowed = ", ".join(str(r) for r in writable_roots())
    raise AccessDenied(
        f"Приложению запрещено изменять файлы вне своей рабочей папки: {resolved}. "
        f"Разрешено только: {allowed}"
    )
