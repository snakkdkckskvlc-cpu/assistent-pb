"""Чтение таблиц из XLSX: строки позиций и понимание, какая колонка что значит.

Сметы, акты и накладные приходят в произвольном виде: своя шапка, свои
названия колонок, объединённые ячейки, шапка не с первой строки, итог внизу.
Требовать от бухгалтера «укажите, что колонка D — это количество» значит
переложить на человека работу, ради снятия которой функция и делается.

Поэтому колонки определяются сами, а результат ОБЯЗАН быть показан человеку до
сравнения: определение по названиям колонок — догадка, и молча считать по ней
нельзя. Функция возвращает и разложенные строки, и то, как она их поняла.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import TYPE_CHECKING

from openpyxl import load_workbook

from ...services.table_compare import Row, parse_number

if TYPE_CHECKING:
    from pathlib import Path

# Как одну и ту же колонку называют в смете, акте, накладной и выгрузке из 1С.
# Порядок внутри набора значения не имеет, порядок наборов — имеет: сначала
# ищется сумма, потом цена, иначе «стоимость» уедет в цену.
_HEADERS: tuple[tuple[str, tuple[str, ...]], ...] = (
    (
        "название",
        (
            "наименование",
            "название",
            "номенклатура",
            "позиция",
            "работы",
            "видработ",
            "наименованиеработ",
            "материал",
            "предмет",
            "описание",
            "товар",
        ),
    ),
    (
        "сумма",
        ("сумма", "суммавсего", "всего", "итого", "стоимость", "суммасндс", "суммабезндс"),
    ),
    ("цена", ("цена", "ценазаед", "ценазаединицу", "расценка", "стоимостьединицы")),
    (
        "количество",
        ("количество", "колво", "кол", "объем", "число", "количествоед"),
    ),
    ("единица", ("едизм", "единица", "единицаизмерения", "ед")),
)

# Строки, которые выглядят как позиция, но ею не являются. Без них итог сметы
# попадает в сравнение отдельной «позицией» и удваивает сумму.
_NOT_A_POSITION = re.compile(
    r"^\s*(итого|всего|итог|в\s*том\s*числе|ндс|сумма\s+ндс|к\s+оплате|"
    r"стоимость\s+работ|по\s+смете|раздел|подраздел)\b",
    re.IGNORECASE,
)

_CLEAN_HEADER = re.compile(r"[^а-яa-z0-9]+")


def _header_key(value: object) -> str:
    return _CLEAN_HEADER.sub("", str(value or "").strip().casefold().replace("ё", "е"))


# Ячейка ЦЕЛИКОМ число, а не «число где-то внутри». Для определения типа
# колонки это принципиально: parse_number намеренно нестрогий, он вытаскивает
# 1234.56 из «1 234,56 ₽» — и он же находит 3 в «Кабель ВВГнг 3х1,5». По
# нестрогой проверке колонка с наименованиями считалась числовой, и разбор
# файла без шапки возвращал ноль строк.
# Разделители разрядов: обычный пробел, неразрывный, узкий неразрывный,
# апостроф — в выгрузках из 1С и Excel встречаются все.
_PURE_NUMBER = re.compile(r"^-?\d[\d   ' ]*(?:[.,]\d+)?$")


def _is_number(cell: object) -> bool:
    if isinstance(cell, bool):
        return False
    if isinstance(cell, int | float):
        return True
    return bool(_PURE_NUMBER.match(str(cell).strip()))


@dataclass
class Разбор:
    """Что удалось прочитать и как это было понято."""

    строки: list[Row] = field(default_factory=list)
    лист: str = ""
    строка_шапки: int | None = None
    колонки: dict[str, int] = field(default_factory=dict)  # роль → номер колонки, с 1
    заголовки: list[str] = field(default_factory=list)
    пропущено_итогов: int = 0
    # Итоговые строки файла: («ИТОГО», сумма в копейках). Позициями они не
    # считаются, но проверке арифметики нужны — с ними сверяется сумма строк.
    итоги: list[tuple[str, int | None]] = field(default_factory=list)
    # Весь текст листа одной строкой. Нужен, чтобы найти сумму прописью:
    # она пишется свободным текстом где угодно, а не в колонке таблицы.
    текст: str = ""

    @property
    def шапка_найдена(self) -> bool:
        return self.строка_шапки is not None and "название" in self.колонки

    @property
    def предупреждения(self) -> list[str]:
        """Человеческим языком — где программа догадывалась.

        Показывается ДО сравнения. Молча посчитать по неверно угаданной колонке
        и выдать отчёт — худший исход: он выглядит правильным.
        """
        out: list[str] = []
        if not self.шапка_найдена:
            out.append(
                "Не удалось понять, где в файле шапка таблицы — колонки выбраны "
                "по первому подходящему столбцу. Проверьте разбор перед сверкой."
            )
        if "количество" not in self.колонки:
            out.append("Колонка с количеством не найдена — сверяться будут только суммы.")
        if "сумма" not in self.колонки:
            out.append("Колонка с суммой не найдена — сверяться будет только количество.")
        if not self.строки:
            out.append("В файле не нашлось ни одной строки с наименованием.")
        return out


def _sheet_rows(path: Path, sheet: str | None) -> tuple[str, list[list[object]]]:
    # data_only=True — нужны ПОСЧИТАННЫЕ значения формул, а не сами формулы.
    # В сметах сумма почти всегда формула, и без этого флага в ячейке приедет
    # строка «=D5*E5», которую не с чем сравнивать.
    #
    # read_only=True держит в памяти одну строку вместо всей книги: сметы на
    # несколько тысяч строк — обычное дело, а сервер один на тридцать человек.
    book = load_workbook(filename=str(path), data_only=True, read_only=True)
    try:
        ws = book[sheet] if sheet and sheet in book.sheetnames else book[book.sheetnames[0]]
        rows = [list(r) for r in ws.iter_rows(values_only=True)]
        return str(ws.title), rows
    finally:
        book.close()


def _find_header(rows: list[list[object]], limit: int = 25) -> tuple[int | None, dict[str, int]]:
    """Строка шапки и роли колонок. Ищем ту строку, где ролей опознано больше.

    Ограничение в 25 строк намеренное: у смет сверху бывает «шапка документа»
    на десяток строк с реквизитами, но настоящая таблица начинается близко.
    Искать по всему файлу — значит рано или поздно принять за шапку строку
    данных, где случайно встретилось слово «материал».
    """
    лучшая: tuple[int, dict[str, int]] | None = None
    for i, row in enumerate(rows[:limit]):
        роли: dict[str, int] = {}
        for j, cell in enumerate(row, start=1):
            key = _header_key(cell)
            if not key:
                continue
            for роль, варианты in _HEADERS:
                if роль in роли:
                    continue
                if key in варианты or any(key.startswith(v) for v in варианты):
                    роли[роль] = j
                    break
        if "название" in роли and (лучшая is None or len(роли) > len(лучшая[1])):
            лучшая = (i, роли)
    return (лучшая[0], лучшая[1]) if лучшая else (None, {})


def _guess_columns(rows: list[list[object]]) -> dict[str, int]:
    """Запасной путь, когда шапки нет вовсе.

    Название — колонка с наибольшим числом текстовых ячеек. Числовые колонки
    берутся по правилу «последняя — сумма, предпоследняя — количество»: так
    устроено большинство печатных форм. Это ДОГАДКА, и она обязана дойти до
    человека предупреждением — см. Разбор.предупреждения.
    """
    ширина = max((len(r) for r in rows), default=0)
    текстовых = [0] * (ширина + 1)
    числовых = [0] * (ширина + 1)
    for row in rows:
        for j, cell in enumerate(row, start=1):
            if cell is None or str(cell).strip() == "":
                continue
            if _is_number(cell):
                числовых[j] += 1
            else:
                текстовых[j] += 1
    if not any(текстовых[1:]):
        return {}
    роли = {"название": текстовых.index(max(текстовых[1:]))}
    числовые_колонки = [j for j in range(1, ширина + 1) if числовых[j] > 0]
    if числовые_колонки:
        роли["сумма"] = числовые_колонки[-1]
    if len(числовые_колонки) > 1:
        роли["количество"] = числовые_колонки[-2]
    return роли


def _cell(row: list[object], колонки: dict[str, int], роль: str) -> object:
    j = колонки.get(роль)
    return row[j - 1] if j is not None and j <= len(row) else None


def read_table(path: Path, *, sheet: str | None = None) -> Разбор:
    """Читает лист и раскладывает его на строки позиций."""
    лист, rows = _sheet_rows(path, sheet)
    строка_шапки, колонки = _find_header(rows)
    if строка_шапки is None:
        колонки = _guess_columns(rows)

    разбор = Разбор(лист=лист, строка_шапки=строка_шапки, колонки=колонки)
    разбор.текст = "\n".join(
        " ".join(str(c) for c in row if c is not None and str(c).strip()) for row in rows
    )
    if строка_шапки is not None:
        разбор.заголовки = [str(c or "").strip() for c in rows[строка_шапки]]
    if "название" not in колонки:
        return разбор

    начало = (строка_шапки + 1) if строка_шапки is not None else 0
    кол_назв = колонки["название"]
    for номер, row in enumerate(rows[начало:], start=начало + 1):
        if кол_назв > len(row):
            continue
        название = str(row[кол_назв - 1] or "").strip()
        if not название:
            continue
        if _NOT_A_POSITION.match(название):
            # Итоговая строка. Считать её позицией — значит удвоить сумму: она
            # и так равна сумме строк выше. Но саму цифру запоминаем: с ней
            # сверяется сумма строк в проверке арифметики.
            разбор.пропущено_итогов += 1
            разбор.итоги.append((название, parse_number(_cell(row, колонки, "сумма"), scale=100)))
            continue

        разбор.строки.append(
            Row(
                номер=номер,
                название=название,
                количество=parse_number(_cell(row, колонки, "количество"), scale=1000),
                сумма=parse_number(_cell(row, колонки, "сумма"), scale=100),
                цена=parse_number(_cell(row, колонки, "цена"), scale=100),
            )
        )
    return разбор


def read_grid(path: Path, *, sheet: str | None = None) -> tuple[str, list[list[object]]]:
    """Лист как есть: имя и таблица значений, без разбора на позиции.

    Нужен проверкам, которые смотрят на ЯЧЕЙКИ, а не на позиции сметы: реестр
    контрагентов — не смета, «наименования» в нём может не быть вовсе, и
    read_table вернул бы по нему ноль строк.
    """
    return _sheet_rows(path, sheet)


def sheet_names(path: Path) -> list[str]:
    """Листы книги — чтобы человек выбрал, если их несколько."""
    book = load_workbook(filename=str(path), data_only=True, read_only=True)
    try:
        return list(book.sheetnames)
    finally:
        book.close()
