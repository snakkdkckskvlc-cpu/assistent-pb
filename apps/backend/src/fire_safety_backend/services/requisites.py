"""Проверка реквизитов по контрольным суммам. Чистые функции, база не нужна.

Зачем. Реквизиты попадают в исходящие документы: ИНН и расчётный счёт — в
письмо на фирменном бланке, ОКПО организации — в шапку путевого листа, СНИЛС
водителя — в его обязательные графы. Опечатка в цифре не выглядит опечаткой:
номер той же длины из тех же цифр, и заметить её глазами нельзя. Дальше
документ уходит контрагенту, а платёж — не туда.

Контрольная сумма ловит именно это: перестановку соседних цифр, замену одной
цифры, потерянный разряд. Она НЕ проверяет, что счёт существует и принадлежит
этой организации, — такой проверки офлайн не бывает вовсе. Поэтому все функции
отвечают «похоже на настоящий» / «точно испорчен», и текст отказа написан для
секретаря, а не для программиста.

Ноль обращений к базе и к сети — это условие, а не случайность: функции зовутся
на каждый ввод в форме, и поход в SQLite на нажатие клавиши ощущается.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Проверка:
    """Результат. `причина` пуста, когда всё хорошо."""

    ok: bool
    причина: str = ""

    def __bool__(self) -> bool:
        return self.ok


ХОРОШО = Проверка(True)


def _цифры(значение: object) -> str:
    """Оставляет только цифры: реквизиты копируют с пробелами и дефисами."""
    return "".join(ch for ch in str(значение or "") if ch.isdigit())


def _контроль(цифры: str, веса: tuple[int, ...]) -> int:
    return sum(в * int(ц) for в, ц in zip(веса, цифры, strict=False)) % 11 % 10


_ИНН10 = (2, 4, 10, 3, 5, 9, 4, 6, 8)
_ИНН12_11 = (7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
_ИНН12_12 = (3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8)


def проверить_инн(значение: object) -> Проверка:
    """ИНН организации (10 цифр) или человека (12).

    Пустое значение ошибкой не считается: обязательность решает форма, а не эта
    функция. Иначе проверка мешала бы заполнять карточку по частям.
    """
    d = _цифры(значение)
    if not d:
        return ХОРОШО
    if len(d) == 10:
        ok = _контроль(d, _ИНН10) == int(d[9])
    elif len(d) == 12:
        ok = _контроль(d, _ИНН12_11) == int(d[10]) and _контроль(d, _ИНН12_12) == int(d[11])
    else:
        return Проверка(False, "ИНН — это 10 цифр у организации или 12 у человека")
    return (
        ХОРОШО if ok else Проверка(False, "ИНН не сходится по контрольной цифре — проверьте номер")
    )


def проверить_кпп(значение: object) -> Проверка:
    """КПП: девять знаков, контрольной суммы у него нет вовсе.

    Пятый и шестой знак могут быть латинскими буквами — так записывают учёт
    иностранных организаций. Поэтому здесь не `_цифры`, а разбор по позициям.
    """
    s = str(значение or "").strip()
    if not s:
        return ХОРОШО
    плохо = Проверка(
        False,
        "КПП — девять знаков: четыре цифры, потом две цифры или латинские буквы, потом три цифры",
    )
    if len(s) != 9:
        return плохо
    if not (s[:4].isdigit() and s[6:].isdigit()):
        return плохо
    середина = s[4:6]
    if not all(ch.isdigit() or ("A" <= ch <= "Z") for ch in середина):
        return плохо
    return ХОРОШО


def проверить_бик(значение: object) -> Проверка:
    """БИК: девять цифр, российские начинаются с «04»."""
    d = _цифры(значение)
    if not d:
        return ХОРОШО
    if len(d) != 9:
        return Проверка(False, "БИК — это девять цифр")
    if d[:2] != "04":
        return Проверка(False, "БИК российского банка начинается с «04»")
    return ХОРОШО


_СЧЁТ_ВЕСА = (7, 1, 3) * 8  # хватает на 23 разряда проверяемой строки


def проверить_счёт(значение: object, бик: object) -> Проверка:
    """Расчётный или корреспондентский счёт — только вместе с БИК.

    Контрольная сумма счёта считается НЕ по самому счёту: в неё входят три
    цифры из БИК. Поэтому проверить счёт в отрыве от банка нельзя, и функция
    честно требует оба значения.

    Какие именно три цифры — зависит от вида счёта. У корреспондентского
    (начинается с 301) берут «0» и пятый-шестой знаки БИК, у остальных —
    последние три знака БИК. Перепутать нельзя: правильный счёт объявит себя
    испорченным.
    """
    счёт = _цифры(значение)
    b = _цифры(бик)
    if not счёт:
        return ХОРОШО
    if len(счёт) != 20:
        return Проверка(False, "Номер счёта — это 20 цифр")
    if len(b) != 9:
        return Проверка(False, "Чтобы проверить счёт, нужен БИК банка — он тоже вводится")

    префикс = "0" + b[4:6] if счёт.startswith("301") else b[6:9]
    строка = префикс + счёт
    сумма = sum((в * int(ц)) % 10 for в, ц in zip(_СЧЁТ_ВЕСА, строка, strict=False))
    if сумма % 10 != 0:
        return Проверка(
            False, "Счёт не сходится с БИК — проверьте обе цифры: ошибка может быть в любой из них"
        )
    return ХОРОШО


def проверить_огрн(значение: object) -> Проверка:
    """ОГРН организации (13 цифр) или предпринимателя (15)."""
    d = _цифры(значение)
    if not d:
        return ХОРОШО
    if len(d) == 13:
        ок = int(d[:12]) % 11 % 10 == int(d[12])
    elif len(d) == 15:
        ок = int(d[:14]) % 13 % 10 == int(d[14])
    else:
        return Проверка(False, "ОГРН — 13 цифр у организации или 15 у предпринимателя")
    return ХОРОШО if ок else Проверка(False, "ОГРН не сходится по контрольной цифре")


def проверить_окпо(значение: object) -> Проверка:
    """ОКПО: 8 цифр у организации, 10 у предпринимателя.

    Второй проход со сдвинутыми весами — часть алгоритма, а не запасной путь:
    если первый даёт остаток 10, контрольная цифра считается заново, и только
    после этого десятка превращается в ноль.
    """
    d = _цифры(значение)
    if not d:
        return ХОРОШО
    if len(d) not in (8, 10):
        return Проверка(False, "ОКПО — восемь цифр у организации или десять у предпринимателя")

    тело, контроль = d[:-1], int(d[-1])
    первый = sum(((i % 10) + 1) * int(ц) for i, ц in enumerate(тело)) % 11
    if первый < 10:
        return (
            ХОРОШО
            if первый == контроль
            else Проверка(False, "ОКПО не сходится по контрольной цифре")
        )
    второй = sum((((i + 2) % 10) + 1) * int(ц) for i, ц in enumerate(тело)) % 11
    ожидаемый = 0 if второй == 10 else второй
    return (
        ХОРОШО
        if ожидаемый == контроль
        else Проверка(False, "ОКПО не сходится по контрольной цифре")
    )


def проверить_снилс(значение: object) -> Проверка:
    """СНИЛС водителя — обязательный реквизит путевого листа.

    Опечатка здесь делает документ дефектным, а замечают её в лучшем случае при
    сдаче: одиннадцать цифр глазами не сверяет никто.

    Номера младше 001-001-998 контрольного числа не имеют — это не ошибка, а
    исторические номера, и отвергать их нельзя.
    """
    d = _цифры(значение)
    if not d:
        return ХОРОШО
    if len(d) != 11:
        return Проверка(False, "СНИЛС — одиннадцать цифр")
    if int(d[:9]) <= 1001998:
        return ХОРОШО

    сумма = sum((9 - i) * int(ц) for i, ц in enumerate(d[:9]))
    ожидаемое = 0 if сумма in (100, 101) else (сумма if сумма < 100 else сумма % 101 % 100)
    return (
        ХОРОШО
        if ожидаемое == int(d[9:])
        else Проверка(False, "СНИЛС не сходится по контрольному числу — проверьте цифры")
    )
