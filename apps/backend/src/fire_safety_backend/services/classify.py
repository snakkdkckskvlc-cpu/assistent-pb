"""Классификатор типа документа — быстрый, детерминированный, без LLM.

Нужен батч-обработке (pipelines/batch.py): юридический анализ имеет смысл
только для договоров, остальные загруженные файлы помечаются типом и
пропускаются, а не гонятся через LLM по несколько минут каждый.

Внешний план предлагал TF-IDF/эмбеддинги, но для четырёх классов с очень
сильными лексическими маркерами («предмет договора», «Уважаемый …!»,
«АКТ выполненных работ», «смета») взвешенные ключевые слова дают тот же
результат мгновенно, офлайн и объяснимо — в ответе видно, какие маркеры
сработали. Усложнять до эмбеддингов стоит, только если на реальных
документах компании появятся классы без явных маркеров.
"""

from __future__ import annotations

# Маркер → вес. Ищется подстрокой в casefold-тексте первых _SCAN_CHARS
# символов (тип документа виден по шапке и первым абзацам).
_MARKERS: dict[str, dict[str, int]] = {
    "договор": {
        "предмет договора": 3,
        "настоящий договор": 3,
        "обязанности сторон": 3,
        "ответственность сторон": 2,
        "реквизиты сторон": 2,
        "именуем": 2,  # «именуемое в дальнейшем …»
        "стороны договорились": 2,
        "договор №": 2,
        "заказчик": 1,
        "подрядчик": 1,
        "исполнитель": 1,
    },
    "письмо": {
        "уважаем": 3,  # «Уважаемый Иван Иванович!»
        "доводим до вашего сведения": 3,
        "направляем в ваш адрес": 3,
        "просим вас": 2,
        "направляем": 2,
        "с уважением": 2,
        "исх. №": 2,
        "просим": 1,
    },
    "акт": {
        "акт №": 3,
        "комиссия в составе": 3,
        "акт выполненных работ": 3,
        "выполненных работ": 2,
        "приемки": 2,
        "приёмки": 2,
        "сдал": 2,
        "принял": 2,
    },
    "смета": {
        "локальная смета": 3,
        "сметный расчет": 3,
        "сметный расчёт": 3,
        "ед. изм": 3,
        "смета": 2,
        "наименование работ": 2,
        "итого по смете": 2,
        "стоимость": 1,
    },
}

_SCAN_CHARS = 4000
# Ниже этой суммы весов уверенного класса нет — «прочее».
_MIN_SCORE = 3


def classify_document(text: str) -> dict:
    """Определяет тип документа: договор / письмо / акт / смета / прочее.

    Возвращает {"type", "confidence" 0..1, "signals": [сработавшие маркеры]}.
    """
    haystack = text[:_SCAN_CHARS].casefold()
    scores: dict[str, int] = {}
    signals: dict[str, list[str]] = {}
    for doc_type, markers in _MARKERS.items():
        score = 0
        hits = []
        for marker, weight in markers.items():
            if marker in haystack:
                score += weight
                hits.append(marker)
        scores[doc_type] = score
        signals[doc_type] = hits

    best = max(scores, key=lambda k: scores[k])
    best_score = scores[best]
    if best_score < _MIN_SCORE:
        return {"type": "прочее", "confidence": 0.0, "signals": []}

    total = sum(scores.values())
    return {
        "type": best,
        "confidence": round(best_score / total, 2) if total else 0.0,
        "signals": signals[best],
    }
