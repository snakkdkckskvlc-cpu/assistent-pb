"""Проверка реквизитов сразу во всей таблице: реестр контрагентов, заявка на оплату.

Отличие от `requisites.py`. Там — чистая арифметика над одним значением, она
зовётся из формы на каждый ввод. Здесь — проход по чужому файлу, который никто
не заполнял в нашем приложении: триста строк, привезённых из 1С, из почты, от
контрагента. Глазами их не проверяет никто, и опечатка в ИНН всплывает через
две недели отказом банка.

Три решения, без которых экран был бы вреден.

**Что проверять — решает шапка, проверять ли — решает само значение.** Колонка
«ИНН» говорит, какую арифметику применять. Но если в ячейке пусто или там текст
вроде «не указан» — это не ошибка контрольной суммы, и молчать о ней надо
по-разному. Иначе экран начинает ругаться на пустые клетки, а на крик перестают
смотреть — тот же урок, что с допусками в арифметике счёта.

**Догадка показывается человеку.** Разбор шапки — догадка, и отчёт называет, что
за какую колонку он принял. Молча посчитать по неверно понятой колонке и выдать
«всё хорошо» — худший исход: он выглядит правильным.

**Ложная тревога дороже пропуска.** Проверка формата (лишние пробелы, латиница
в русском слове, число текстом) идёт по всем ячейкам, но каждая из них выбрана
так, чтобы срабатывать на настоящей беде, а не на стилистике.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import TYPE_CHECKING

from openpyxl.utils import get_column_letter

from . import requisites

if TYPE_CHECKING:
    from pathlib import Path

# Больше этого на экран не отдаём. Не ради экономии: список на десять тысяч
# строк никто не читает, а «первые 500 и сколько всего» человек понимает сразу
# и идёт чинить файл, а не листать отчёт.
ПОТОЛОК_ПРОБЛЕМ = 500

# Сколько верхних строк просматривается в поисках шапки. Столько же берёт
# разбор смет, и по той же причине: ниже начинаются данные, и рано или поздно
# в них попадётся строка со словом «ИНН» внутри текста.
ГЛУБИНА_ПОИСКА_ШАПКИ = 25


@dataclass(frozen=True)
class Проблема:
    строка: int
    колонка: str  # буква столбца, как в Excel
    заголовок: str
    вид: str
    значение: str
    что: str


@dataclass
class Колонка:
    буква: str
    номер: int  # с 1
    заголовок: str
    виды: list[str]


@dataclass
class Результат:
    проблемы: list[Проблема] = field(default_factory=list)
    всего_проблем: int = 0
    строк: int = 0
    ячеек: int = 0
    лист: str = ""
    строка_шапки: int | None = None
    колонки: list[Колонка] = field(default_factory=list)
    заметки: list[str] = field(default_factory=list)

    @property
    def всё_сходится(self) -> bool:
        return self.всего_проблем == 0


# Виды реквизитов и как их называют в шапке. Ключ ищется по ПЕРВОМУ слову
# заголовка, а не вхождением: «ИНН контрагента» и «ИНН/КПП» опознать надо, а
# «Инновации» — нет. Вхождением подстроки последнее тоже совпало бы.
ВИДЫ: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("ИНН", ("инн",)),
    ("КПП", ("кпп",)),
    ("ОГРН", ("огрн", "огрнип")),
    ("ОКПО", ("окпо",)),
    ("СНИЛС", ("снилс",)),
    ("БИК", ("бик",)),
    # Голого «Счёт» в списке нет намеренно. В реестре на оплату эта колонка
    # почти всегда означает НОМЕР СЧЁТА-ФАКТУРЫ, а не банковский счёт, и
    # объявлять её банковской — врать человеку в отчёте о разборе шапки.
    # Цена решения честная: колонку, названную одним словом «Счёт», программа
    # не проверит. Ошибиться в другую сторону дороже.
    (
        "Счёт",
        (
            "рс",
            "рсч",
            "рсчет",
            "расчетный",
            "расчетныйсчет",
            "номерсчета",
            "банковскийсчет",
            "счетполучателя",
            "корсчет",
            "корреспондентскийсчет",
        ),
    ),
    ("Телефон", ("телефон", "тел", "мобильный", "моб")),
)

# Сколько цифр у какого реквизита. Нужно для колонок вида «ИНН/КПП», где в
# одной ячейке лежат оба: разделить их можно только по длине.
ДЛИНЫ: dict[str, tuple[int, ...]] = {
    "ИНН": (10, 12),
    "КПП": (9,),
    "ОГРН": (13, 15),
    "ОКПО": (8, 10),
    "СНИЛС": (11,),
    "БИК": (9,),
    "Счёт": (20,),
    "Телефон": (10, 11),
}

_СЛОВА = re.compile(r"[^0-9a-zA-Zа-яА-ЯёЁ]+")
_РАЗДЕЛИТЕЛИ = re.compile(r"[\s/,;|]+")
_ЧИСЛО_ТЕКСТОМ = re.compile(r"^-?\d{1,3}(?:[   ]?\d{3})*(?:[.,]\d+)?$")

# Буквенный отрезок целиком, а не «слово по границе»: границы слова между
# кириллицей и латиницей нет, и проверка по ним не срабатывала бы никогда.
# Тот же класс ошибки уже ловили в исходниках проекта — см. .claude/hooks.
_БУКВЫ = re.compile(r"[A-Za-zА-Яа-яЁё]{2,}")
_ЕСТЬ_КИРИЛЛИЦА = re.compile(r"[А-Яа-яЁё]")
_ЕСТЬ_ЛАТИНИЦА = re.compile(r"[A-Za-z]")


def _ключи_заголовка(заголовок: str) -> tuple[str, str]:
    """Первое слово и весь заголовок без разделителей.

    Нужны оба. По первому слову опознаётся «ИНН контрагента», по слитному —
    «Р/с», которое на слова разваливается в «р» и «с». Сравнивать вхождением
    подстроки нельзя: тогда «Инновации» становится колонкой ИНН, и весь столбец
    с названиями уезжает в проверку контрольных сумм.
    """
    низ = заголовок.strip().casefold().replace("ё", "е")
    слова = [с for с in _СЛОВА.split(низ) if с]
    return (слова[0] if слова else ""), "".join(слова)


def _виды_колонки(заголовок: str) -> list[str]:
    """Какие реквизиты живут в этой колонке. Обычно один, у «ИНН/КПП» — два."""
    низ = заголовок.casefold().replace("ё", "е")
    первое, слитно = _ключи_заголовка(заголовок)
    найдено: list[str] = []
    for вид, ключи in ВИДЫ:
        if первое in ключи or слитно in ключи:
            найдено.append(вид)
            continue
        # Второй и дальше реквизит в составном заголовке — только по явному
        # разделителю: «ИНН/КПП», «ИНН и КПП». Без разделителя это обычный
        # текст, и принимать его за колонку нельзя.
        if найдено and any(f"/{к}" in низ or f" {к}" in низ for к in ключи):
            найдено.append(вид)
    return найдено


def _цифры(текст: str) -> str:
    return "".join(ch for ch in текст if ch.isdigit())


# Меньше этого числа цифр — не испорченный счёт, а что-то другое. Колонка
# «Счёт» в реестре платежей сплошь и рядом означает НОМЕР СЧЁТА-ФАКТУРЫ:
# «СЧ-00123», «142/А». Без этого порога экран ругался бы на каждую такую
# строку двадцатизначным требованием, и первым же файлом потерял бы доверие.
# Настоящая опечатка в банковском счёте даёт 19–21 цифру и порог проходит.
МИНИМУМ_ЦИФР_В_СЧЁТЕ = 15


def _проверить_значение(вид: str, значение: str, бик: str) -> str:
    """Пустая строка — всё хорошо, иначе человеческая причина."""
    if вид == "Счёт":
        if len(_цифры(значение)) < МИНИМУМ_ЦИФР_В_СЧЁТЕ:
            return ""
        return requisites.проверить_счёт(значение, бик).причина
    if вид == "Телефон":
        d = _цифры(значение)
        if len(d) not in (10, 11):
            return "Телефон — 10 цифр без кода страны или 11 с ним"
        return ""
    проверка = {
        "ИНН": requisites.проверить_инн,
        "КПП": requisites.проверить_кпп,
        "ОГРН": requisites.проверить_огрн,
        "ОКПО": requisites.проверить_окпо,
        "СНИЛС": requisites.проверить_снилс,
        "БИК": requisites.проверить_бик,
    }[вид]
    return проверка(значение).причина


def _разложить(виды: list[str], значение: str) -> list[tuple[str, str]]:
    """Пары «вид — кусок значения» для колонки, где реквизитов несколько.

    Куски разбираются ПО ДЛИНЕ, а не по порядку: в жизни встречается и
    «ИНН/КПП», и «КПП/ИНН», и только ИНН без КПП. Порядок в шапке ничего не
    гарантирует, длина — гарантирует.
    """
    if len(виды) == 1:
        return [(виды[0], значение)]
    куски = [к for к in _РАЗДЕЛИТЕЛИ.split(значение.strip()) if к]
    пары: list[tuple[str, str]] = []
    свободные = list(виды)
    for кусок in куски:
        длина = len(_цифры(кусок))
        подходит = next((в for в in свободные if длина in ДЛИНЫ.get(в, ())), None)
        if подходит is None:
            # Кусок не подошёл ни под один реквизит колонки. Приписываем его
            # первому виду — пусть его проверка и объяснит человеку, что не так
            # с длиной: своё сообщение здесь было бы хуже, оно не знает вида.
            пары.append((свободные[0] if свободные else виды[0], кусок))
            continue
        свободные.remove(подходит)
        пары.append((подходит, кусок))
    return пары


def _смешанный_алфавит(текст: str) -> str:
    """Первое слово, где кириллица и латиница перемешаны. Пусто — если таких нет."""
    for m in _БУКВЫ.finditer(текст):
        слово = m.group()
        if _ЕСТЬ_КИРИЛЛИЦА.search(слово) and _ЕСТЬ_ЛАТИНИЦА.search(слово):
            return слово
    return ""


def _найти_шапку(rows: list[list[object]]) -> tuple[int | None, list[Колонка]]:
    лучшая: tuple[int, list[Колонка]] | None = None
    for i, row in enumerate(rows[:ГЛУБИНА_ПОИСКА_ШАПКИ]):
        колонки: list[Колонка] = []
        for j, cell in enumerate(row, start=1):
            заголовок = str(cell or "").strip()
            if not заголовок:
                continue
            виды = _виды_колонки(заголовок)
            if виды:
                колонки.append(Колонка(get_column_letter(j), j, заголовок, виды))
        if колонки and (лучшая is None or len(колонки) > len(лучшая[1])):
            лучшая = (i, колонки)
    return (лучшая[0], лучшая[1]) if лучшая else (None, [])


def проверить(path: Path, *, sheet: str | None = None) -> Результат:
    """Проходит лист и собирает всё, что не сходится."""
    from ..infrastructure.parsers import xlsx_parser

    лист, rows = xlsx_parser.read_grid(path, sheet=sheet)
    строка_шапки, колонки = _найти_шапку(rows)
    итог = Результат(лист=лист, строка_шапки=строка_шапки, колонки=колонки)

    начало = (строка_шапки + 1) if строка_шапки is not None else 0
    данные = rows[начало:]
    итог.строк = len(данные)

    if not колонки:
        итог.заметки.append(
            "Ни одной колонки с реквизитами не нашлось: в шапке нет ни ИНН, ни КПП, ни "
            "ОГРН, ни СНИЛС, ни БИК, ни счёта. Проверены только пробелы и перепутанные "
            "буквы — если реквизиты в файле есть, назовите колонки в шапке."
        )

    по_номеру = {к.номер: к for к in колонки}
    бик_колонка = next((к for к in колонки if "БИК" in к.виды), None)
    счёт_есть = any("Счёт" in к.виды for к in колонки)
    if счёт_есть and бик_колонка is None:
        итог.заметки.append(
            "Колонка с БИК не найдена, поэтому счета проверены только по длине: "
            "контрольная цифра счёта считается вместе с БИК банка, без него её нет."
        )

    # Числовые колонки: нужны, чтобы поймать «число, записанное текстом».
    # Отдельно — иначе пришлось бы ругаться на каждый текст в таблице.
    числовых: dict[int, int] = {}
    for row in данные:
        for j, cell in enumerate(row, start=1):
            if isinstance(cell, int | float) and not isinstance(cell, bool):
                числовых[j] = числовых.get(j, 0) + 1

    проблемы: list[Проблема] = []

    def добавить(строка: int, номер: int, вид: str, значение: str, что: str) -> None:
        к = по_номеру.get(номер)
        проблемы.append(
            Проблема(
                строка=строка,
                колонка=к.буква if к else get_column_letter(номер),
                заголовок=к.заголовок if к else "",
                вид=вид,
                значение=значение,
                что=что,
            )
        )

    for сдвиг, row in enumerate(данные):
        номер_строки = начало + сдвиг + 1  # как показывает Excel, с единицы
        бик = ""
        if бик_колонка is not None and бик_колонка.номер <= len(row):
            бик = str(row[бик_колонка.номер - 1] or "").strip()

        for j, cell in enumerate(row, start=1):
            if cell is None:
                continue
            текст = str(cell).strip()
            if not текст:
                continue
            итог.ячеек += 1

            к = по_номеру.get(j)
            if к is not None:
                for вид, кусок in _разложить(к.виды, текст):
                    причина = _проверить_значение(вид, кусок, бик)
                    if причина:
                        добавить(номер_строки, j, вид, кусок, причина)

            слово = _смешанный_алфавит(текст)
            if слово:
                добавить(
                    номер_строки,
                    j,
                    "Буквы",
                    текст,
                    f"В слове «{слово}» русские и латинские буквы вперемешку — "
                    f"поиск и группировка такую строку не найдут",
                )

            исходный = str(cell)
            if исходный != исходный.strip() or "  " in исходный:
                добавить(номер_строки, j, "Пробелы", текст, "Лишние пробелы по краям или внутри")

            # «Число текстом» — только там, где в колонке есть и настоящие
            # числа. Колонка сплошь из текста числовой не является, и ругаться
            # на неё не за что.
            if isinstance(cell, str) and числовых.get(j, 0) > 0 and _ЧИСЛО_ТЕКСТОМ.match(текст):
                добавить(
                    номер_строки,
                    j,
                    "Число",
                    текст,
                    "Число записано текстом — в суммы и сортировку такая ячейка не попадёт",
                )

    итог.всего_проблем = len(проблемы)
    итог.проблемы = проблемы[:ПОТОЛОК_ПРОБЛЕМ]
    if итог.всего_проблем > ПОТОЛОК_ПРОБЛЕМ:
        итог.заметки.append(
            f"Показаны первые {ПОТОЛОК_ПРОБЛЕМ} замечаний из {итог.всего_проблем}. "
            f"Исправьте их и загрузите файл снова."
        )
    if строка_шапки is None and колонки:
        итог.заметки.append("Шапка таблицы не найдена — проверены все строки подряд.")
    return итог
