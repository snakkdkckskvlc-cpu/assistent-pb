"""Сверка двух таблиц: что должно быть против того, что предъявлено.

Задача из карты информационного потока, шаг 30 — «Сверка по смете и Акту».
Сегодня прораб и куратор заказчика сверяют две бумаги глазами, вдвоём. Не
поймали расхождение здесь — оно всплывает у заказчика на приёмке закрывающих,
и круг подготовки и подписи повторяется вместе с ещё одним визитом куратора.
Это самая дорогая ошибка в карте.

Тот же движок закрывает счёт против накладной и ведомость против выгрузки.

## Модель здесь не участвует

Ни одна цифра в отчёте не произведена языковой моделью, и это не осторожность,
а условие работоспособности. Проверить пятьсот сгенерированных ячеек дороже,
чем набить их руками; проверить одно правило — минута. Сопоставление имён
делает нормализация, сравнение — арифметика.

## Лучше не сопоставить, чем сопоставить неверно

Несопоставленная строка попадает человеку на глаза и стоит ему минуты.
Неверно сопоставленная молча превращает две разные позиции в одну, и отчёт
говорит «всё сошлось» там, где не сошлось. Поэтому автоматически склеиваются
только строки с СОВПАДАЮЩИМ нормализованным именем. Похожие — не склеиваются,
а показываются как кандидаты: решает человек, и его решение запоминается
(services/compare_memory.py), чтобы второй раз не спрашивать.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# Всё, что может стоять между числом и его разрядами: обычный пробел,
# неразрывный, узкий неразрывный и апостроф. В выгрузках из 1С и Excel
# встречаются все четыре, и без них «1 234,56» не разбирается в число.
_SPACES = "   '"
_NUM_RE = re.compile(rf"-?\d[\d{_SPACES} ]*(?:[.,]\d+)?")

# Разделители размера: «3х1.5» пишут кириллической х, латинской x, звёздочкой
# и знаком умножения. Для склада это одна и та же позиция.
_MULT_RE = re.compile(r"[x×*]", re.IGNORECASE)

_PUNCT_RE = re.compile(r"[\"'«»„“”(),;:]+")
_SPACE_RE = re.compile(r"\s+")


def parse_number(raw: object, *, scale: int) -> int | None:
    """Число из ячейки в целых долях. None — ячейка пустая или не число.

    Целые, а не float: суммы складываются сотнями строк, и погрешность даёт
    расхождение с бухгалтерией, которое нечем объяснить. Копейки — scale=100,
    количества — scale=1000 (тысячные доли, как в схеме CRM).
    """
    if raw is None:
        return None
    if isinstance(raw, bool):  # True в ячейке числом не считаем
        return None
    if isinstance(raw, int):
        return raw * scale
    if isinstance(raw, float):
        return round(raw * scale)

    text = str(raw).strip()
    if not text:
        return None
    match = _NUM_RE.search(text)
    if match is None:
        return None
    cleaned = match.group(0)
    for space in _SPACES + " ":
        cleaned = cleaned.replace(space, "")
    cleaned = cleaned.replace(",", ".")
    try:
        return round(float(cleaned) * scale)
    except ValueError:
        return None


def normalize(name: object) -> str:
    """Ключ сопоставления. Совпал ключ — это одна и та же позиция.

    Правила подобраны по тому, как одна позиция пишется в смете, у поставщика
    и в накладной. Каждое убирает различие, которое ТОЧНО не меняет смысла:

      «Кабель ВВГнг 3х1,5»  «кабель ввгнг 3x1.5»  «КАБЕЛЬ ВВГ нг 3*1,5»

    Чего здесь намеренно НЕТ — склейки по похожести, отбрасывания слов и
    сокращений. «Труба 25» и «Труба 32» отличаются одним символом, и любое
    «умное» приведение сделает их одной позицией. Похожие имена разбираются
    отдельно, с участием человека.
    """
    text = str(name or "").strip().casefold()
    if not text:
        return ""
    text = text.replace("ё", "е")
    # ПОРЯДОК ВАЖЕН. Десятичная запятая приводится к точке ПЕРВОЙ: чистка знаков
    # препинания заменяет запятую на пробел, и «3х1,5» превращалось в «3х1 5»,
    # то есть в другой ключ, чем «3x1.5». Ловится тестом на четыре написания
    # одного кабеля.
    text = re.sub(r"(?<=\d),(?=\d)", ".", text)
    text = _PUNCT_RE.sub(" ", text)
    # Разделитель размера к одному виду, без пробелов вокруг: «3 х 1,5» → «3х1.5»
    text = _MULT_RE.sub("х", text)
    text = re.sub(r"\s*х\s*", "х", text)
    # Дефис между буквой и буквой — это «ВВГ-нг» против «ВВГнг». Между цифрами
    # не трогаем: «25-32» это диапазон, а не описка.
    text = re.sub(r"(?<=[а-яa-z])-(?=[а-яa-z])", "", text)
    return _SPACE_RE.sub(" ", text).strip()


_DIGITS_RE = re.compile(r"\d+(?:\.\d+)?")


def similarity(a: str, b: str) -> float:
    """Похожесть двух нормализованных имён, 0..1.

    Считается по общим словам и общим тройкам символов, без внешних библиотек
    и без модели. Нужна ТОЛЬКО чтобы предложить человеку кандидата, никогда —
    чтобы склеить строки самостоятельно.

    Числа решают. В названии материала число — это почти всегда типоразмер, и
    «Труба 25» с «Трубой 32» текстом похожи на девяносто процентов, а на складе
    это две разные позиции. Поэтому если наборы чисел РАСХОДЯТСЯ (ни один не
    вложен в другой), похожесть режется до заведомо непроходной.

    Вложенность, а не равенство: у одной строки часто есть лишние числа —
    номер ГОСТа, артикул, год. «Кабель 3х1.5» и «Кабель 3х1.5 по ГОСТ 31996»
    это одна позиция, и {3, 1.5} ⊂ {3, 1.5, 31996}.
    """
    if not a or not b:
        return 0.0
    if a == b:
        return 1.0

    na, nb = set(_DIGITS_RE.findall(a)), set(_DIGITS_RE.findall(b))
    противоречие = bool(na) and bool(nb) and not (na <= nb or nb <= na)

    wa, wb = set(a.split()), set(b.split())
    words = len(wa & wb) / len(wa | wb) if wa | wb else 0.0

    def grams(s: str) -> set[str]:
        s = f"  {s} "
        return {s[i : i + 3] for i in range(len(s) - 2)}

    ga, gb = grams(a), grams(b)
    chars = len(ga & gb) / len(ga | gb) if ga | gb else 0.0

    score = 0.45 * words + 0.55 * chars
    return score * 0.3 if противоречие else score


@dataclass(frozen=True)
class Row:
    """Строка таблицы, приведённая к сравнимому виду."""

    номер: int
    название: str
    количество: int | None = None  # тысячные доли
    сумма: int | None = None  # копейки
    # Цена за единицу, копейки. Сверке таблиц не нужна, поэтому по умолчанию
    # пусто; её использует проверка арифметики: цена × количество = сумма.
    цена: int | None = None

    @property
    def ключ(self) -> str:
        return normalize(self.название)


@dataclass
class Пара:
    слева: Row
    справа: Row

    @property
    def разница_количества(self) -> int | None:
        if self.слева.количество is None or self.справа.количество is None:
            return None
        return self.справа.количество - self.слева.количество

    @property
    def разница_суммы(self) -> int | None:
        if self.слева.сумма is None or self.справа.сумма is None:
            return None
        return self.справа.сумма - self.слева.сумма

    @property
    def сходится(self) -> bool:
        return not self.разница_количества and not self.разница_суммы


@dataclass
class Кандидат:
    """Похожие строки. Решение за человеком, автоматически не склеиваются."""

    слева: Row
    справа: Row
    похожесть: float


@dataclass
class Отчёт:
    сошлось: list[Пара] = field(default_factory=list)
    расхождения: list[Пара] = field(default_factory=list)
    только_слева: list[Row] = field(default_factory=list)
    только_справа: list[Row] = field(default_factory=list)
    кандидаты: list[Кандидат] = field(default_factory=list)
    дубли_слева: list[Row] = field(default_factory=list)
    дубли_справа: list[Row] = field(default_factory=list)

    @property
    def итог_слева(self) -> int:
        return sum(r.сумма or 0 for r in self._все_слева)

    @property
    def итог_справа(self) -> int:
        return sum(r.сумма or 0 for r in self._все_справа)

    @property
    def расхождение_итогов(self) -> int:
        return self.итог_справа - self.итог_слева

    @property
    def _все_слева(self) -> list[Row]:
        return (
            [p.слева for p in self.сошлось + self.расхождения]
            + self.только_слева
            + self.дубли_слева
            + [k.слева for k in self.кандидаты]
        )

    @property
    def _все_справа(self) -> list[Row]:
        return (
            [p.справа for p in self.сошлось + self.расхождения]
            + self.только_справа
            + self.дубли_справа
            + [k.справа for k in self.кандидаты]
        )

    @property
    def всё_сошлось(self) -> bool:
        """Сошлось — это когда человеку не осталось ни одного решения.

        Кандидаты входят сюда наравне с расхождениями, и это не придирка:
        нерешённый кандидат означает, что две строки, возможно, одна позиция, а
        возможно, разные. Отчёт «всё сошлось» при нерешённых кандидатах — та
        самая молчаливая деградация, после которой документ уходит заказчику.
        Поймано тестом test_similar_rows_are_candidates_not_matches.
        """
        return not (
            self.расхождения
            or self.только_слева
            or self.только_справа
            or self.дубли_слева
            or self.дубли_справа
            or self.кандидаты
        )


# Ниже этого порога кандидат человеку не показывается: список из сотни
# «похожих» строк никто читать не станет, и функция превратится в шум.
#
# ЗАМЕРЕНО на двенадцати парах из номенклатуры пожарной безопасности:
#
#   должны предлагаться      0.438 … 0.728   (варианты написания одной позиции)
#   не должны                0.000 … 0.562   (разные позиции)
#
# Диапазоны ПЕРЕСЕКАЮТСЯ, и порога, который их разделяет, не существует.
# Виновник один и он показателен: «Монтаж трубопровода» против «Демонтаж
# трубопровода» — 0.562, выше, чем у настоящих вариантов написания. Текстово
# это почти одна строка, по смыслу — противоположные работы.
#
# Порог 0.42 выбран так, чтобы НЕ ТЕРЯТЬ настоящие варианты (нижний из них
# 0.438), сознательно пропуская ложных кандидатов вроде монтажа с демонтажом.
# Это допустимо ровно потому, что кандидат — предложение человеку, а не
# склейка: ложный стоит одного взгляда, потерянный настоящий — ручного поиска
# по всей таблице. Автоматически склеиваются ТОЛЬКО точные совпадения ключа.
#
# Улучшать это стоит не подкруткой веса, а памятью соответствий: подтверждённая
# пара второй раз уже не спрашивается.
ПОРОГ_ПОХОЖЕСТИ = 0.42


def compare(
    слева: list[Row],
    справа: list[Row],
    *,
    синонимы: dict[str, str] | None = None,
    порог: float = ПОРОГ_ПОХОЖЕСТИ,
) -> Отчёт:
    """Сверяет две таблицы.

    `синонимы` — подтверждённые человеком соответствия «нормализованный ключ →
    канонический ключ». Со второго раза позиция сопоставляется молча.

    Дубли внутри одной таблицы не сопоставляются вовсе, а выносятся отдельно:
    если в акте позиция встречается дважды, неизвестно, какую из строк сверять
    со сметой, и любой выбор здесь был бы выдумкой. Человек сначала объединяет
    строки у себя.
    """
    syn = синонимы or {}

    def ключ(row: Row) -> str:
        k = row.ключ
        return syn.get(k, k)

    отчёт = Отчёт()

    def разложить(rows: list[Row]) -> tuple[dict[str, Row], list[Row]]:
        по_ключу: dict[str, Row] = {}
        дубли: dict[str, list[Row]] = {}
        for row in rows:
            k = ключ(row)
            if not k:
                continue
            if k in по_ключу:
                дубли.setdefault(k, [по_ключу[k]]).append(row)
            else:
                по_ключу[k] = row
        for k in дубли:
            по_ключу.pop(k, None)
        return по_ключу, [r for rows_ in дубли.values() for r in rows_]

    л, отчёт.дубли_слева = разложить(слева)
    п, отчёт.дубли_справа = разложить(справа)

    for k, row_л in л.items():
        row_п = п.get(k)
        if row_п is None:
            continue
        пара = Пара(слева=row_л, справа=row_п)
        (отчёт.сошлось if пара.сходится else отчёт.расхождения).append(пара)

    осталось_л = [r for k, r in л.items() if k not in п]
    осталось_п = [r for k, r in п.items() if k not in л]

    # Кандидаты подбираются жадно и только парами «один к одному»: одна строка
    # слева не может быть кандидатом сразу к трём справа — человек всё равно
    # выберет одну, а список станет нечитаемым.
    занято: set[int] = set()
    for row_л in осталось_л:
        лучший: Кандидат | None = None
        лучший_индекс = -1
        for i, row_п in enumerate(осталось_п):
            if i in занято:
                continue
            s = similarity(ключ(row_л), ключ(row_п))
            if s >= порог and (лучший is None or s > лучший.похожесть):
                лучший = Кандидат(слева=row_л, справа=row_п, похожесть=s)
                лучший_индекс = i
        if лучший is not None:
            занято.add(лучший_индекс)
            отчёт.кандидаты.append(лучший)

    сопоставлено_л = {id(k.слева) for k in отчёт.кандидаты}
    сопоставлено_п = {id(k.справа) for k in отчёт.кандидаты}
    отчёт.только_слева = [r for r in осталось_л if id(r) not in сопоставлено_л]
    отчёт.только_справа = [r for r in осталось_п if id(r) not in сопоставлено_п]

    отчёт.кандидаты.sort(key=lambda k: k.похожесть, reverse=True)
    return отчёт
