"""Проверка арифметики в счёте, акте или смете.

Бухгалтер получает документ и пересчитывает его на калькуляторе: сходится ли
цена, умноженная на количество; равна ли сумма строк итогу; верно ли посчитан
НДС; совпадает ли сумма прописью с цифрами. Это полчаса на документ и полная
сосредоточенность, а ошибка всё равно проскакивает — потому что глаз
привыкает.

Здесь всё это делает арифметика. Языковая модель не участвует: она нужна там,
где надо понять текст, а не там, где надо сложить столбик. Проверить пятьсот
чисел, посчитанных моделью, дороже, чем сложить их самому.

## Что считается ошибкой, а что нет

Копейка расхождения — не ошибка, а округление: в счёте 0,1% НДС от 33 копеек
даёт хвост, который каждая программа округляет по-своему. Порог поставлен в
одну копейку на строку и рубль на итог; всё, что больше, показывается человеку.

Чего здесь нет и быть не должно — исправления. Программа говорит, где не
сходится, и не трогает документ: подставить «правильную» цифру в чужой счёт
значит взять на себя ответственность за него.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# Порог, ниже которого расхождение считается округлением, а не ошибкой.
# В копейках.
ДОПУСК_СТРОКА = 1
ДОПУСК_ИТОГ = 100  # рубль

# Ставки НДС, действующие в РФ. 20 — основная, 10 — льготная (продукты,
# лекарства, детские товары), 0 — экспорт. Для монтажа систем пожаротушения
# всегда 20, но список полный: программа продаётся и другим компаниям.
СТАВКИ_НДС = (20, 10, 0)

_ЕДИНИЦЫ_М = ("", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")
_ЕДИНИЦЫ_Ж = ("", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")
_ОТ_10_ДО_19 = (
    "десять",
    "одиннадцать",
    "двенадцать",
    "тринадцать",
    "четырнадцать",
    "пятнадцать",
    "шестнадцать",
    "семнадцать",
    "восемнадцать",
    "девятнадцать",
)
_ДЕСЯТКИ = (
    "",
    "",
    "двадцать",
    "тридцать",
    "сорок",
    "пятьдесят",
    "шестьдесят",
    "семьдесят",
    "восемьдесят",
    "девяносто",
)
_СОТНИ = (
    "",
    "сто",
    "двести",
    "триста",
    "четыреста",
    "пятьсот",
    "шестьсот",
    "семьсот",
    "восемьсот",
    "девятьсот",
)


def _тройка(число: int, женский: bool) -> list[str]:
    слова: list[str] = []
    сотни, остаток = divmod(число, 100)
    if сотни:
        слова.append(_СОТНИ[сотни])
    if 10 <= остаток <= 19:
        слова.append(_ОТ_10_ДО_19[остаток - 10])
    else:
        десятки, единицы = divmod(остаток, 10)
        if десятки:
            слова.append(_ДЕСЯТКИ[десятки])
        if единицы:
            слова.append((_ЕДИНИЦЫ_Ж if женский else _ЕДИНИЦЫ_М)[единицы])
    return слова


def _склонение(число: int, один: str, два: str, много: str) -> str:
    сотня, десяток = число % 100, число % 10
    if 11 <= сотня <= 14:
        return много
    if десяток == 1:
        return один
    if 2 <= десяток <= 4:
        return два
    return много


def прописью(копейки: int) -> str:
    """«1234,56» → «одна тысяча двести тридцать четыре рубля 56 копеек».

    Так это пишут в счетах и актах: рубли словами, копейки цифрами. Нужно,
    чтобы сравнить с тем, что напечатано в документе, — расхождение между
    цифрами и прописью банк считает основанием не проводить платёж.
    """
    рубли, коп = divmod(abs(int(копейки)), 100)
    if рубли == 0:
        слова = ["ноль"]
    else:
        слова = []
        # Разряды: миллиарды, миллионы, тысячи, рубли. Тысячи — женского рода
        # («одна тысяча», а не «один тысяча»), остальные мужского.
        разряды = (
            (1_000_000_000, False, ("миллиард", "миллиарда", "миллиардов")),
            (1_000_000, False, ("миллион", "миллиона", "миллионов")),
            (1_000, True, ("тысяча", "тысячи", "тысяч")),
        )
        остаток = рубли
        for множитель, женский, формы in разряды:
            часть, остаток = divmod(остаток, множитель)
            if часть:
                слова += _тройка(часть, женский)
                слова.append(_склонение(часть, *формы))
        if остаток:
            слова += _тройка(остаток, False)
    слова.append(_склонение(рубли, "рубль", "рубля", "рублей"))
    знак = "минус " if копейки < 0 else ""
    return f"{знак}{' '.join(w for w in слова if w)} {коп:02d} {_склонение(коп, 'копейка', 'копейки', 'копеек')}"


_ЧИСТКА = re.compile(r"[^а-я0-9 ]+")

# Слова, из которых состоит сумма прописью. Нужны, чтобы отрезать её от того,
# что написано рядом: «Всего к оплате: семнадцать тысяч рублей 00 копеек».
#
# ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ПРОВЕРИТЬ «содержится ли». «два рубля 00 копеек»
# содержится в «двадцать два рубля 00 копеек» — то есть документ на двадцать
# два рубля прошёл бы проверку на два. Поэтому сумма вырезается целиком и
# сравнивается целиком.
_СЛОВА_СУММЫ = frozenset(
    list(_ЕДИНИЦЫ_М)
    + list(_ЕДИНИЦЫ_Ж)
    + list(_ОТ_10_ДО_19)
    + list(_ДЕСЯТКИ)
    + list(_СОТНИ)
    + [
        "ноль",
        "тысяча",
        "тысячи",
        "тысяч",
        "миллион",
        "миллиона",
        "миллионов",
        "миллиард",
        "миллиарда",
        "миллиардов",
        "рубль",
        "рубля",
        "рублей",
        "копейка",
        "копейки",
        "копеек",
        "минус",
    ]
) - {""}


def _вырезать_сумму(приведённый: str) -> str:
    """Оставляет от фразы только саму сумму прописью.

    Берётся самый длинный ХВОСТ из слов-числительных: в документах перед
    суммой пишут «Всего к оплате», «Сумма прописью», «Итого», а после неё —
    ничего. Цифры (копейки) тоже считаются частью суммы.
    """
    слова = приведённый.split()
    начало = len(слова)
    for i in range(len(слова) - 1, -1, -1):
        if слова[i] in _СЛОВА_СУММЫ or слова[i].isdigit():
            начало = i
        else:
            break
    return " ".join(слова[начало:])


def _сравнимо(текст: str) -> str:
    """Приводит фразу к виду, в котором её можно сравнить.

    В документах пишут «Двести девяносто две тысячи ... рублей 00 копеек»,
    «...(двести девяносто две тысячи) руб. 00 коп.», с разным регистром и
    сокращениями. Сравнивать посимвольно бессмысленно.
    """
    t = str(текст or "").casefold().replace("ё", "е")
    t = t.replace("руб.", "рублей").replace("коп.", "копеек")
    t = _ЧИСТКА.sub(" ", t)
    return re.sub(r"\s+", " ", t).strip()


@dataclass
class Проблема:
    """Одно расхождение, найденное в документе."""

    где: str
    что: str
    ожидалось: int | None = None  # копейки
    в_документе: int | None = None  # копейки
    строка: int | None = None

    @property
    def разница(self) -> int | None:
        if self.ожидалось is None or self.в_документе is None:
            return None
        return self.в_документе - self.ожидалось


@dataclass
class Результат:
    проблемы: list[Проблема] = field(default_factory=list)
    строк_проверено: int = 0
    сумма_строк: int = 0
    итог_в_документе: int | None = None
    ндс_в_документе: int | None = None
    прописью_в_документе: str = ""
    заметки: list[str] = field(default_factory=list)

    @property
    def всё_сходится(self) -> bool:
        return not self.проблемы


def _найти_прописью(текст: str) -> str:
    """Достаёт из документа сумму, написанную словами.

    Ищется по слову «рубл» с числительными перед ним: это единственный
    надёжный признак. Брать всю строку целиком нельзя — рядом обычно стоят
    реквизиты и подписи.
    """
    for кусок in re.split(r"[\n;]", текст):
        приведённый = _сравнимо(кусок)
        if re.search(r"\b(рубль|рубля|рублей)\b", приведённый) and re.search(
            r"\b(ноль|один|одна|две|два|три|четыре|пять|шесть|семь|восемь|девять|"
            r"десять|двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|"
            r"восемьдесят|девяносто|сто|двести|триста|четыреста|пятьсот|шестьсот|"
            r"семьсот|восемьсот|девятьсот|тысяч|миллион)\b",
            приведённый,
        ):
            return кусок.strip()
    return ""


def проверить(разбор) -> Результат:
    """Пересчитывает документ. Возвращает список расхождений.

    `разбор` — результат чтения файла (infrastructure/parsers/xlsx_parser).
    """
    итог = Результат()
    итог.строк_проверено = len(разбор.строки)

    # 1. По каждой строке: цена × количество = сумма.
    for r in разбор.строки:
        if r.цена is None or r.количество is None or r.сумма is None:
            continue
        # Количество хранится в тысячных долях, цена и сумма — в копейках.
        ожидалось = round(r.цена * r.количество / 1000)
        if abs(ожидалось - r.сумма) > ДОПУСК_СТРОКА:
            итог.проблемы.append(
                Проблема(
                    где="строка",
                    что=f"«{r.название}»: цена × количество не даёт сумму",
                    ожидалось=ожидалось,
                    в_документе=r.сумма,
                    строка=r.номер,
                )
            )

    # 2. Сумма строк против итога, напечатанного в документе.
    итог.сумма_строк = sum(r.сумма or 0 for r in разбор.строки)
    итоги_с_числами = [(т, с) for т, с in разбор.итоги if с is not None]
    ндс_строки = [(т, с) for т, с in итоги_с_числами if "ндс" in т.casefold()]
    общие = [(т, с) for т, с in итоги_с_числами if "ндс" not in т.casefold()]

    if общие:
        # Берём НАИБОЛЬШИЙ из общих итогов: в документах их бывает несколько
        # («Итого по разделу», «Всего»), и настоящий — самый большой.
        подпись, значение = max(общие, key=lambda p: p[1])
        итог.итог_в_документе = значение
        if abs(значение - итог.сумма_строк) > ДОПУСК_ИТОГ:
            итог.проблемы.append(
                Проблема(
                    где="итог",
                    что=f"Сумма строк не сходится с «{подпись}»",
                    ожидалось=итог.сумма_строк,
                    в_документе=значение,
                )
            )
    else:
        итог.заметки.append(
            "В документе не нашлось итоговой строки — сверять сумму строк не с чем."
        )

    # 3. НДС. Проверяется, только если он выделен отдельной строкой.
    if ндс_строки:
        подпись, значение = ндс_строки[0]
        итог.ндс_в_документе = значение
        ставка = _ставка_из_подписи(подпись)
        база = итог.итог_в_документе or итог.сумма_строк
        if ставка is not None and база:
            # «в том числе НДС» — налог сидит внутри суммы; «сверху» — снаружи.
            внутри = "в том числе" in подпись.casefold() or "в т.ч" in подпись.casefold()
            ожидалось = (
                round(база * ставка / (100 + ставка)) if внутри else round(база * ставка / 100)
            )
            if abs(ожидалось - значение) > ДОПУСК_ИТОГ:
                итог.проблемы.append(
                    Проблема(
                        где="ндс",
                        что=f"«{подпись}» посчитан неверно для ставки {ставка}%",
                        ожидалось=ожидалось,
                        в_документе=значение,
                    )
                )
        elif ставка is None:
            итог.заметки.append(f"В строке «{подпись}» не указана ставка НДС — проверить её нечем.")

    # 4. Сумма прописью против цифр.
    фраза = _найти_прописью(разбор.текст)
    итог.прописью_в_документе = фраза
    if фраза:
        эталон = итог.итог_в_документе if итог.итог_в_документе is not None else итог.сумма_строк
        if _вырезать_сумму(_сравнимо(фраза)) != _сравнимо(прописью(эталон)):
            итог.проблемы.append(
                Проблема(
                    где="прописью",
                    что="Сумма прописью не совпадает с цифрами. "
                    f"По цифрам должно быть: {прописью(эталон)}",
                    ожидалось=эталон,
                )
            )
    else:
        итог.заметки.append("Суммы прописью в документе не нашлось — сверять нечего.")

    return итог


_СТАВКА = re.compile(r"(\d{1,2})\s*%")


def _ставка_из_подписи(подпись: str) -> int | None:
    """Ставка НДС из текста строки: «в том числе НДС 20%» → 20."""
    m = _СТАВКА.search(подпись)
    if m is None:
        return None
    ставка = int(m.group(1))
    return ставка if ставка in СТАВКИ_НДС else None
